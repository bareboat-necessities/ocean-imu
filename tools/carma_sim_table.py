#!/usr/bin/env python3
"""Generate the deterministic last-900 s simulation table for the CARMA filter.

The three-axis CARMA counterpart of ``tools/ou_sim_table.py`` and
``tools/tfg_sim_table.py``.  The record list is imported from the OU-III module,
so all three filters are scored on the same eight records in the same order.

The CARMA prior changes the horizontal channels as much as the vertical one, so
the table reports X, Y and Z error as a percentage of the incident H_s, the 3D
error and the attitude.  The protocol is the historical deterministic one: one
realization per record, default seeds, the final 900 s of a 20-minute replay of
the default variant A41.  The multi-seed paired comparison with OU-III is the
committed dataset benchmark in reports/results/carma3_benchmark/.

Usage:

    python3 tools/carma_sim_table.py \\
        --binary tests/kalman_carma/carma3-sim \\
        --data-dir plots/kalman_carma \\
        --output doc/kalman_carma/carma-sim-results-generated.tex-part
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "tools"))

# Same eight records, same order, as the OU-III and TFG deterministic tables.
from ou_sim_table import RECORDS, FLOAT  # noqa: E402

PATTERNS = {
    "pct_hs": re.compile(rf"XYZ RMS \(%Hs\): X=({FLOAT})% Y=({FLOAT})% Z=({FLOAT})%"),
    "d3": re.compile(rf"3D RMS \(m\): ({FLOAT}) \(3D % of max \|disp_ref\|_3D = ({FLOAT})%"),
    "angles": re.compile(rf"Angles RMS \(deg\): Roll=({FLOAT}) Pitch=({FLOAT}) Yaw=({FLOAT})"),
}


def run_record(binary: Path, record: Path) -> dict[str, Any]:
    """Replay one record and pull the last-900 s block out of the output."""
    binary = binary.resolve()
    record = record.resolve()
    env = {k: v for k, v in os.environ.items() if not k.startswith("W3D_")}
    env["W3D_WRITE_TIMESERIES"] = "0"
    # Score every record, including any that trips a gate.  The table reports
    # what the filter did, not whether it passed.
    env["W3D_COLLECT_ALL_GATES"] = "1"
    completed = subprocess.run(
        [str(binary), "--input", str(record)],
        cwd=binary.parent,
        env=env,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        check=False,
    )
    out = completed.stdout
    row: dict[str, Any] = {}
    for name, pattern in PATTERNS.items():
        match = pattern.search(out)
        if match is None:
            tail = "\n".join(out.splitlines()[-25:])
            raise RuntimeError(f"{record.name}: simulator output has no {name}\n{tail}")
        row[name] = tuple(float(value) for value in match.groups())
    return row


CARMA3_TABLE = {
    "tool": "tools/carma_sim_table.py",
    "variant": "variant A41",
    "caption": "Three-axis CARMA(4,1) simulation results (last \\SI{900}{s} RMS window).",
    "label": "tab:carma_sim_results",
}


def format_table(rows: list[tuple[str, float, dict[str, Any]]], table: dict[str, str] = CARMA3_TABLE) -> str:
    """The results table; ``table`` names the generator, variant, caption and label.

    tools/tfg_carma_sim_table.py formats the TFG-CARMA3 table with its own.
    """
    lines = [
        f"% Generated by {table['tool']} -- do not edit by hand.",
        "%",
        "% Single-realization deterministic protocol: default seeds, final 900 s",
        f"% of a 20-minute replay of {table['variant']}.  Not a multi-seed study.",
        "% Requires: \\usepackage{booktabs,siunitx,adjustbox}",
        "\\begin{table}[t]",
        "  \\centering",
        f"  \\caption{{{table['caption']}}}",
        f"  \\label{{{table['label']}}}",
        "  \\setlength{\\tabcolsep}{3pt}",
        "  \\renewcommand{\\arraystretch}{1.08}",
        "  \\footnotesize",
        "  \\sisetup{detect-all}",
        "  \\begin{adjustbox}{max width=\\columnwidth}",
        "  \\begin{tabular}{@{}l",
        "                  S[table-format=1.2]",
        "                  S[table-format=1.2]",
        "                  S[table-format=1.2]",
        "                  S[table-format=1.2]",
        "                  S[table-format=1.2]",
        "                  S[table-format=1.2]",
        "                  S[table-format=1.2]",
        "                  S[table-format=1.2]",
        "                  @{}}",
        "    \\toprule",
        "    {Case} & {$H_s$} & {X} & {Y} & {Z} & {3D} &",
        "    {Roll} & {Pitch} & {Yaw} \\\\",
        "    {} & {\\si{m}} & {\\%$H_s$} & {\\%$H_s$} & {\\%$H_s$} & {\\%} &",
        "    {\\si{deg}} & {\\si{deg}} & {\\si{deg}} \\\\",
        "    \\midrule",
    ]
    for label, hs, row in rows:
        x_pct, y_pct, z_pct = row["pct_hs"]
        d3_pct = row["d3"][1]
        roll, pitch, yaw = row["angles"]
        lines.append(
            f"    {label} & {hs:.2f} & {x_pct:.2f} & {y_pct:.2f} & {z_pct:.2f} & {d3_pct:.2f} & "
            f"{roll:.2f} & {pitch:.2f} & {yaw:.2f} \\\\"
        )
    lines += [
        "    \\bottomrule",
        "  \\end{tabular}",
        "  \\end{adjustbox}",
        "\\end{table}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", default="tests/kalman_carma/carma3-sim")
    parser.add_argument("--data-dir", default="plots/kalman_carma")
    parser.add_argument("--output", default="doc/kalman_carma/carma-sim-results-generated.tex-part")
    args = parser.parse_args()

    def resolve(p: str) -> Path:
        return Path(p) if Path(p).is_absolute() else REPO_ROOT / p

    binary, data_dir, output = resolve(args.binary), resolve(args.data_dir), resolve(args.output)
    if not binary.exists():
        print(f"simulator not found: {binary}", file=sys.stderr)
        return 1
    rows: list[tuple[str, float, dict[str, Any]]] = []
    for label, hs, name in RECORDS:
        record = data_dir / name
        if not record.exists():
            print(f"record not found: {record}", file=sys.stderr)
            return 1
        rows.append((label, hs, run_record(binary, record)))
        print(f"scored {name}", file=sys.stderr)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(format_table(rows), encoding="utf-8")
    print(f"wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
