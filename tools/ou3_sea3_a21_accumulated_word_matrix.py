#!/usr/bin/env python3
"""Restartable complete-SEA3 A21 generalized matrix certificate.

This certificate fixes the remaining active-mode Riccati bridge without a
source replacement, replay, eta9 packet condition, or arbitrary P0 rectangle.
It works on the recurrent covariance class generated by the canonical complete
SEA3 Normal-Live word.

The proof has two source-uniform ingredients on the same 3 s word:

1. A finite-memory covariance estimator gives marginal bounds ``u_i`` at the
   word endpoint.  In A mode the first 18 bounds already pay the finite active
   b_a nuisance; the last three use the shipping GM stationary/release bound.
   We do *not* pretend those marginals form a diagonal Loewner bound.  For any
   PSD 21x21 covariance P with ``P_ii <= u_i``, normalize by
   ``D=diag(u_i)``.  The normalized PSD matrix has trace <=21, hence

       P <= 21 D.

   Thus ``Sigma_bar = 21 diag(u_i)`` is a rigorous full-state Loewner upper,
   including every unknown cross covariance.

2. The process recursion injects a block-diagonal independent subnoise.  We
   retain 256 shipping predictions (1.28 s) from the 3 s word for the
   attitude/gyro-bias and translation blocks.  Translation uses the exact
   integrated-OU covariance ``Q(T)`` in the same conditioned 4x4 basis used by
   the validated shipping process primitive.  Attitude/gyro-bias uses the exact
   doubling identity on its scaled two-state lower comparison.  The active b_a
   block needs only the final shipping GM process injection, which is already
   many orders stronger than the 1e-18 comparison.

Every intervening shipping measurement is allowed.  For a Joseph correction,
for any implemented gain K,

  (I-KH) Omega (I-KH)' + K R K'
      >= (Omega^-1 + H' R^-1 H)^-1.

We upper the *complete* measurement information by a block-diagonal matrix.
For the accelerometer row, whose A-mode columns lie in theta, a_w and b_a,

  ||H_theta x + H_aw y + z||_R^2
     <= 3( ||H_theta x||_R^2 + ||H_aw y||_R^2 + ||z||_R^2 ),

so the factor three rigorously pays every cross block.  S=0 contributes only to
S and magnetometer only to theta.  Applying this upper information to the
retained independent process subnoise yields a block-diagonal lower comparison
for the actual word-injected Omega.

The final test is *one full 21x21 interval LDLT* after a block-diagonal
congruence.  It certifies the inverse-space form exactly equivalent to

    Omega_word - delta P_word >> 0,  delta=1e-18,

for every endpoint covariance in the recurrent complete-SEA3 Loewner tube.
The block structure is used only to build rigorous full-matrix lower/upper
comparisons; no blockwise minimum or scalar contraction ratio can promote P3.
"""
