def I(x: float) -> Interval:
    return Interval.outward_bounds(float(x), float(x))


def _zero(n: int) -> IntervalMatrix:
    z = I(0.0)
    return [[z for _ in range(n)] for _ in range(n)]


def _FI(q: Fraction) -> Interval:
    x = float(q)
    return Interval.outward_bounds(x, x)


# Exact rational conditioning of the x->0 integrated-OU process shape.
F = Fraction
_L_INV = (
    (F(1), F(0), F(0), F(0)),
    (-F(3, 8), F(1), F(0), F(0)),
    (F(1, 15), -F(4, 9), F(1), F(0)),
    (-F(15, 2), F(30), -F(105, 2), F(1)),
)
_R_DIAG = (F(1), F(10), F(100), F(2))
_C_RATIONAL = tuple(
    tuple(_R_DIAG[i] * _L_INV[i][j] for j in range(4))
    for i in range(4)
)
_C = [[_FI(v) for v in row] for row in _C_RATIONAL]
_CT = matrix_transpose(_C)


def _diag(values: list[float]) -> IntervalMatrix:
    A = _zero(len(values))
    for i, v in enumerate(values):
        A[i][i] = I(v)
    return A


def _full_A21_marginal_upper(path: Path, dynamic: dict, process: dict, hinfo: dict, adet: dict) -> dict:
    """Recurrent A21 marginal upper at exactly the canonical 3 s endpoint."""
    domain = json.loads(path.read_text(encoding="utf-8"))
    live = domain["normal_live"]
    axis_factors = TUBE._axis_factors()
    trans, timing = H18._same_word_translation_upper(dynamic, live, axis_factors)
    import ou3_vector_uco_certificate as VECTOR
    vector = VECTOR.build()
    vf = VECTOR.validate(vector)
    if vf:
        raise RuntimeError(f"vector covariance upper invalid: {vf}")
    full = TUBE._global_full_state_upper(
        dynamic,
        live,
        vector,
        process,
        float(hinfo["eta6_information_lower"]),
        trans,
        timing,
    )
    H = [float(x) for x in full["H"]]
    pba = float(adet["active_bias_process"]["uniform_release_and_active_variance_upper"])
    A = H + [pba, pba, pba]
    if len(A) != DIM or any(not (math.isfinite(x) and x > 0.0) for x in A):
        raise RuntimeError("A21 marginal covariance upper invalid")
    if float(timing["same_word_endpoint_s"]) != WORD_HORIZON_S:
        raise RuntimeError("A21 covariance upper escaped 3 s word endpoint")
    # PSD normalized by diag(u) has diagonal <=1 and therefore lambda_max <= trace <= n.
    loewner_diag = [TUBE.up(DIM * x) for x in A]
    return {
        "marginal_variance_upper": A,
        "Loewner_diagonal_upper": loewner_diag,
        "Loewner_proof": "P<=21*diag(u): normalized PSD has trace<=21",
        "unknown_cross_covariances_covered": True,
        "active_ba_uniform_variance_upper": pba,
        "timing": timing,
        "translation": trans,
    }


def _translation_inverse_space_condition(
    x_total: Interval,
    *,
    sigma_floor: float,
    horizon: float,
    sigma_upper_physical: list[float],
    info_S_physical: float,
    info_aw_physical: float,
) -> IntervalMatrix:
    """Return I-delta*G*(Omega^-1+D)*G for one translation axis."""
    Qs = FACTORED.step_scaled_q(x_total)
    Oc = matrix_symmetric_hull(matrix_mul(matrix_mul(_C, Qs), _CT))
    Ocinv = matrix_inverse_gauss_jordan(Oc)
    Oinv = matrix_symmetric_hull(matrix_mul(matrix_mul(_CT, Ocinv), _C))

    scales = [
        TUBE.down(sigma_floor * horizon),
        TUBE.down(sigma_floor * horizon * horizon),
        TUBE.down(sigma_floor * horizon * horizon * horizon),
        TUBE.down(sigma_floor),
    ]
    roots = [
        TUBE.up(math.sqrt(sigma_upper_physical[i]) / scales[i])
        for i in range(4)
    ]
    Dscaled = [
        0.0,
        0.0,
        TUBE.up(info_S_physical * scales[2] * scales[2]),
        TUBE.up(info_aw_physical * scales[3] * scales[3]),
    ]
    A = matrix_symmetric_hull(matrix_add(Oinv, _diag(Dscaled)))
    M = _zero(4)
    delta = I(USEFUL_GATE)
    for i in range(4):
        for j in range(4):
            term = I(roots[i]) * A[i][j] * I(roots[j])
            M[i][j] = (I(1.0) if i == j else I(0.0)) - delta * term
    return matrix_symmetric_hull(M)


def _attitude_bias_inverse_space_condition(
    *,
    process: dict,
    h: float,
    steps: int,
    sigma_theta_upper: float,
    sigma_bg_upper: float,
    theta_info_physical_per_sample: float,
) -> tuple[IntervalMatrix, dict]:
    ab = process["attitude_gyro_bias"]
    qtheta = float(ab["theta_diagonal_lower"])
    qbias = float(ab["gyro_bias_diagonal_lower"])
    cross = float(ab["cross_norm_upper"])
    rho = TUBE.down(1.0 - TUBE.up(cross / TUBE.down(math.sqrt(qtheta * qbias))))
    if not (0.0 < rho <= 1.0):
        raise RuntimeError("scaled attitude/bias process lower lost positivity")
    coupling = TUBE.up(h * TUBE.up(math.sqrt(TUBE.up(qbias / TUBE.down(qtheta)))))
    doublings = int(round(math.log2(steps)))
    if 2 ** doublings != steps:
        raise RuntimeError("accumulated step count must be a power of two")
    Phi = [[I(1.0), I(-coupling)], [I(0.0), I(1.0)]]
    Q = [[I(rho), I(0.0)], [I(0.0), I(rho)]]
    Omega = WORDNOISE.accumulate_word_noise(Q, Phi, doublings)
    Oinv = matrix_inverse_gauss_jordan(matrix_symmetric_hull(Omega))
    Dtheta = TUBE.up(float(steps) * theta_info_physical_per_sample * qtheta)
    A = matrix_symmetric_hull(matrix_add(Oinv, _diag([Dtheta, 0.0])))
    roots = [
        TUBE.up(math.sqrt(sigma_theta_upper / qtheta)),
        TUBE.up(math.sqrt(sigma_bg_upper / qbias)),
    ]
    M = _zero(2)
    delta = I(USEFUL_GATE)
    for i in range(2):
        for j in range(2):
            term = I(roots[i]) * A[i][j] * I(roots[j])
            M[i][j] = (I(1.0) if i == j else I(0.0)) - delta * term
    return matrix_symmetric_hull(M), {
        "scaled_process_rho_lower": rho,
        "scaled_bias_coupling_per_step": coupling,
        "theta_information_scaled_upper": Dtheta,
    }


def _ba_inverse_space_condition(
    *,
    process: dict,
    sigma_ba_upper: float,
    ba_info_physical: float,
) -> tuple[Interval, dict]:
    # Retain only the last shipping GM injection; older injections are PSD and
    # may be dropped. Applying the whole-word information upper to that one
    # injection is conservative because it can only make the lower smaller.
    qba = float(process["active_accelerometer_bias"]["Q_accel_bias_lambda_min_lower"])
    inv_plus_info = TUBE.up(1.0 / qba + ba_info_physical)
    value = TUBE.down(1.0 - TUBE.up(USEFUL_GATE * sigma_ba_upper * inv_plus_info))
    return I(value), {
        "one_sample_Q_ba_lower": qba,
        "whole_word_ba_information_upper": ba_info_physical,
        "inverse_space_diagonal_lower": value,
    }


def _assemble_full(Matt: IntervalMatrix, Mtrans: IntervalMatrix, Mba: Interval) -> IntervalMatrix:
    M = _zero(DIM)
    for axis in range(3):
        ai = [axis, 3 + axis]
        for i in range(2):
            for j in range(2):
                M[ai[i]][ai[j]] = Matt[i][j]
        ti = [OFF_V + axis, OFF_P + axis, OFF_S + axis, OFF_AW + axis]
        for i in range(4):
            for j in range(4):
                M[ti[i]][ti[j]] = Mtrans[i][j]
        M[OFF_BA + axis][OFF_BA + axis] = Mba
    return matrix_symmetric_hull(M)


def _split_cell(x: Interval) -> tuple[Interval, Interval]:
    mid = math.sqrt(x.lo * x.hi)
    return Interval.outward_bounds(x.lo, mid), Interval.outward_bounds(mid, x.hi)


def build(domain_path: Path = DEFAULT_DOMAIN) -> dict:
    path = Path(domain_path).resolve()
    complete = COMPLETE.build(path)
    dynamic = DYNAMIC.build(path)
    process = PROCESS.build()
    hinfo = HINFO.build(path)
    adet = ADET.build(path)
    pe = PE.build(path)
    four = FOUR.build(path)
    event = EVENT.build()
    bad = {
        "complete": COMPLETE.validate(complete),
        "dynamic": DYNAMIC.validate(dynamic),
        "process": PROCESS.validate(process),
        "H18_information": HINFO.validate(hinfo),
        "A21_detectability": ADET.validate(adet),
        "PE": PE.validate(pe),
        "four_S": FOUR.validate(four),
        "event_algebra": EVENT.validate(event),
        "word_noise_algebra": WORDNOISE.validate_algebra(),
    }
    bad = {k: v for k, v in bad.items() if v}
    if bad:
        raise RuntimeError(f"A21 accumulated-word prerequisites failed: {bad}")
    if complete["canonical_P3_source"] != "COMPLETE_SEA3_NORMAL_LIVE_WORD":
        raise RuntimeError("A21 accumulated-word certificate detached from complete SEA3")
    if float(complete["word_horizon_s"]) != WORD_HORIZON_S:
        raise RuntimeError("canonical complete SEA3 word is no longer 3 s")
    if adet["eta9_point_packet_shortcut_used"] is not False:
        raise RuntimeError("eta9 shortcut re-entered A21 accumulated-word proof")

    pbar = _full_A21_marginal_upper(path, dynamic, process, hinfo, adet)
    ub = pbar["Loewner_diagonal_upper"]

    h = float(dynamic["validated_rate_and_jump_bounds"]["dt_s"])
    horizon = TUBE.down(ACCUMULATED_STEPS * h)
    if not (0.0 < horizon < WORD_HORIZON_S):
        raise RuntimeError("accumulated subnoise horizon does not fit complete word")
    sigma_floor = float(dynamic["dynamic_invariant"]["sigma_aw_filter_mps2"][0])
    if not sigma_floor > 0.0:
        raise RuntimeError("SEA3 sigma floor lost positivity")

    meas = pe["measurement_runtime"]
    ra = float(meas["accelerometer_variance_upper"])
    rm = float(meas["magnetometer_variance_upper"])
    domain = json.loads(path.read_text(encoding="utf-8"))
    live = domain["normal_live"]
    fhi = float(live["specific_force_norm_upper_mps2"])
    mhi = float(live["magnetic_vector_norm_upper_uT"])
    if not all(x > 0.0 for x in (ra, rm, fhi, mhi)):
        raise RuntimeError("measurement information envelope invalid")

    # Factor three pays every accelerometer theta/a_w/b_a information cross term.
    accel_partition_factor = 3.0
    theta_info_per_sample = TUBE.up(
        accel_partition_factor * fhi * fhi / ra + mhi * mhi / rm
    )
    aw_info_physical = TUBE.up(float(ACCUMULATED_STEPS) * accel_partition_factor / ra)
    ba_info_physical = TUBE.up(float(ACCUMULATED_STEPS) * accel_partition_factor / ra)

    rs_lo = float(dynamic["dynamic_invariant"]["R_S_applied"][0])
    axis_factor_min = min(map(float, four["R_S_axis_std_factors"]))
    rs_std_min = TUBE.down(rs_lo * axis_factor_min)
    # At most one due-S update is executed per valid IMU sample.
    s_updates_upper = ACCUMULATED_STEPS
    info_S_physical = TUBE.up(float(s_updates_upper) / TUBE.down(rs_std_min * rs_std_min))

    Matt, attdiag = _attitude_bias_inverse_space_condition(
        process=process,
        h=h,
        steps=ACCUMULATED_STEPS,
        sigma_theta_upper=float(ub[0]),
        sigma_bg_upper=float(ub[3]),
        theta_info_physical_per_sample=theta_info_per_sample,
    )
    Mba, badiag = _ba_inverse_space_condition(
        process=process,
        sigma_ba_upper=float(ub[OFF_BA]),
        ba_info_physical=ba_info_physical,
    )

    # The already-certified per-step x cover is the same tau coordinate.  Scale
    # each cell by the retained prediction count; recursively subdivide only
    # that same coordinate if the word-horizon interval inverse/LDLT needs it.
    leaves = H18._x_cover(dynamic)
    queue: list[tuple[Interval, int]] = [
        (Interval.outward_bounds(ACCUMULATED_STEPS * x.lo, ACCUMULATED_STEPS * x.hi), 0)
        for x in leaves
    ]
    certified = []
    failures = []
    worst = math.inf
    max_depth = 0
    while queue:
        x, depth = queue.pop()
        max_depth = max(max_depth, depth)
        try:
            Mtrans = _translation_inverse_space_condition(
                x,
                sigma_floor=sigma_floor,
                horizon=horizon,
                sigma_upper_physical=[float(ub[OFF_V]), float(ub[OFF_P]), float(ub[OFF_S]), float(ub[OFF_AW])],
                info_S_physical=info_S_physical,
                info_aw_physical=aw_info_physical,
            )
            Mfull = _assemble_full(Matt, Mtrans, Mba)
            ok, pivots = symmetric_positive_definite_ldlt(Mfull)
        except Exception as exc:
            ok, pivots = False, []
            err = str(exc)
        else:
            err = ""
        if ok:
            pivot = min(p.lo for p in pivots)
            worst = min(worst, pivot)
            certified.append({
                "X_horizon_over_tau": x.as_list(),
                "split_depth": depth,
                "full_21x21_pivot_lower": pivot,
            })
            continue
        if depth < 9:
            left, right = _split_cell(x)
            queue.append((right, depth + 1))
            queue.append((left, depth + 1))
            continue
        failures.append({
            "X_horizon_over_tau": x.as_list(),
            "split_depth": depth,
            "error": err or "full 21x21 LDLT failed",
        })

    closed = not failures and bool(certified) and math.isfinite(worst) and worst > 0.0
    preserve = event["full_matrix_margin_preservation"]
    suffix_preserved = all(bool(preserve[k]) for k in (
        "covers_prediction",
        "covers_every_due_S_update",
        "covers_every_Normal_Live_accelerometer_update",
        "covers_asynchronous_magnetometer_update",
        "covers_immediate_left_error_reset",
        "covers_aw_covariance_floor",
        "covers_not_due_or_rejected_identity_branches",
    ))

    return {
        "schema": SCHEMA,
        "qualification": QUALIFICATION,
        "canonical_source": complete["canonical_P3_source"],
        "complete_word_horizon_s": WORD_HORIZON_S,
        "retained_accumulated_prediction_steps": ACCUMULATED_STEPS,
        "retained_accumulated_horizon_s": horizon,
        "same_complete_SEA3_word_used": True,
        "source_family_replaced": False,
        "trajectory_replay_used": False,
        "independent_tau_sigma_RS_TS_product_used_as_source": False,
        "global_extrema_used_only_as_monotone_nuisance_bounds": True,
        "actual_applied_SpectralMSE_R_S_source_contract_retained": True,
        "all_due_S_updates_remain_in_complete_word": True,
        "recurrent_A21_covariance_upper": pbar,
        "marginal_bounds_misused_as_diagonal_Loewner_upper": False,
        "full_covariance_Loewner_upper_rule": "P<=21*diag(u)",
        "unknown_covariance_cross_terms_covered": True,
        "measurement_information_upper": {
            "accelerometer_partition_factor": accel_partition_factor,
            "theta_information_per_sample_physical_upper": theta_info_per_sample,
            "a_w_whole_retained_horizon_information_physical_upper": aw_info_physical,
            "b_a_whole_retained_horizon_information_physical_upper": ba_info_physical,
            "S_updates_upper": s_updates_upper,
            "R_S_axis_std_lower_for_information_upper": rs_std_min,
            "S_whole_retained_horizon_information_physical_upper": info_S_physical,
            "accelerometer_theta_aw_ba_cross_terms_paid": True,
            "magnetometer_only_theta": True,
            "S_zero_only_S": True,
        },
        "attitude_gyro_bias_block": attdiag,
        "active_ba_block": badiag,
        "translation_word_X_cells_certified": len(certified),
        "translation_word_X_max_split_depth": max_depth,
        "translation_word_X_failures": failures,
        "worst_full_A21_inverse_space_LDLT_pivot_lower": worst if closed else None,
        "full_21x21_interval_LDLT_used": True,
        "full_21x21_generalized_Riccati_matrix_closed": closed,
        "A21_restartable_reachable_tube_contraction_closed": closed,
        "event_algebra_preserves_margin_after_word_closure": suffix_preserved,
        "useful_gate": USEFUL_GATE,
        "eta9_point_packet_shortcut_used": False,
        "blockwise_minimum_ratio_used": False,
        "scalar_beta_contraction_used": False,
        "D_W_L_W_product_used": False,
        "determinant_trace_final_gate_used": False,
        "P3_promoted": False,
        "next_obligation": (
            "bind this restartable A21 matrix closure and the already-closed H18 matrix closure into the sole canonical P3 gate, then execute the literal reset congruence API before promotion"
            if closed else
            "tighten only the same complete-SEA3 accumulated-noise/covariance matrix enclosure; do not relax delta or add eta9/source products"
        ),
    }


def validate(d: dict) -> list[str]:
    f: list[str] = []
    if d.get("schema") != SCHEMA or d.get("qualification") != QUALIFICATION:
        f.append("schema/qualification mismatch")
    if d.get("canonical_source") != "COMPLETE_SEA3_NORMAL_LIVE_WORD":
        f.append("canonical source changed")
    for key in (
        "same_complete_SEA3_word_used",
        "global_extrema_used_only_as_monotone_nuisance_bounds",
        "actual_applied_SpectralMSE_R_S_source_contract_retained",
        "all_due_S_updates_remain_in_complete_word",
        "unknown_covariance_cross_terms_covered",
        "full_21x21_interval_LDLT_used",
        "full_21x21_generalized_Riccati_matrix_closed",
        "A21_restartable_reachable_tube_contraction_closed",
        "event_algebra_preserves_margin_after_word_closure",
    ):
        if d.get(key) is not True:
            f.append(f"{key} is not true")
    for key in (
        "source_family_replaced",
        "trajectory_replay_used",
        "independent_tau_sigma_RS_TS_product_used_as_source",
        "marginal_bounds_misused_as_diagonal_Loewner_upper",
        "eta9_point_packet_shortcut_used",
        "blockwise_minimum_ratio_used",
        "scalar_beta_contraction_used",
        "D_W_L_W_product_used",
        "determinant_trace_final_gate_used",
        "P3_promoted",
    ):
        if d.get(key) is not False:
            f.append(f"forbidden/open flag {key} changed")
    if float(d.get("useful_gate", math.nan)) != USEFUL_GATE:
        f.append("useful gate changed")
    if d.get("full_covariance_Loewner_upper_rule") != "P<=21*diag(u)":
        f.append("A21 Loewner upper rule changed")
    if d.get("translation_word_X_failures"):
        f.append("one or more accumulated-word X cells failed")
    pivot = d.get("worst_full_A21_inverse_space_LDLT_pivot_lower")
    if not isinstance(pivot, (int, float)) or not (math.isfinite(float(pivot)) and float(pivot) > 0.0):
        f.append("full A21 inverse-space LDLT pivot is not strict")
    mi = d.get("measurement_information_upper", {})
    if mi.get("accelerometer_theta_aw_ba_cross_terms_paid") is not True:
        f.append("accelerometer information cross terms not paid")
    if float(mi.get("accelerometer_partition_factor", 0.0)) < 3.0:
        f.append("accelerometer partition factor is too small")
    return list(dict.fromkeys(f))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--domain", type=Path, default=DEFAULT_DOMAIN)
    ap.add_argument("--output", type=Path, required=True)
    args = ap.parse_args()
    d = build(args.domain)
    failures = validate(d)
    d["validation_pass"] = not failures
    d["validation_failures"] = failures
    args.output.parent.mkdir(parents=True, exist_ok=True)
