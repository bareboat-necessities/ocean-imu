def I(x):return Interval.point(float(x))
def finite(x,positive=False):return isinstance(x,Interval) and math.isfinite(x.lo) and math.isfinite(x.hi) and x.lo<=x.hi and (not positive or x.lo>0.0)
def subset(x,bounds):
    lo,hi=map(float,bounds);return x.lo>=lo and x.hi<=hi
def interval_subset(x,outer):return x.lo>=outer.lo and x.hi<=outer.hi

def clamp_interval(x,lo,hi):
    if not finite(x) or not(math.isfinite(lo) and math.isfinite(hi) and lo<=hi):raise ValueError('invalid clamp')
    return Interval(max(lo,min(hi,x.lo)),max(lo,min(hi,x.hi)))
def member_float(text,name):
    m=re.search(rf'\b{name}\s*=\s*([0-9.eE+-]+)f\b',text)
    if not m:raise RuntimeError('cannot extract deployed member '+name)
    return float(m.group(1))
def constants():
    text=WRAPPER.read_text(encoding='utf-8')
    names=('MIN_TUNE_FREQ_HZ','MAX_TUNE_FREQ_HZ','MIN_TAU_S','MAX_TAU_S','MIN_R_S','MAX_R_S','MAX_SIGMA_A','PSEUDO_UPDATE_TAU_RATIO_DEFAULT','PSEUDO_UPDATE_PERIOD_MIN_S_DEFAULT','PSEUDO_UPDATE_PERIOD_MAX_S_DEFAULT','R_S_ACCEL_NOISE_DENSITY_DEFAULT','R_S_MSE_COEFF_DEFAULT')
    c={n:float(SOURCE.parse_const(text,n)) for n in names};c['tau_coeff']=member_float(text,'tau_coeff_');c['sigma_coeff']=member_float(text,'sigma_coeff_');return c

def clamped_frequency(freq,c):
    if not finite(freq,True):raise ValueError('frequency interval must be positive')
    return clamp_interval(freq,c['MIN_TUNE_FREQ_HZ'],c['MAX_TUNE_FREQ_HZ'])
def tau_from_frequency(freq,c):
    f=clamped_frequency(freq,c);raw=I(.5*c['tau_coeff'])/f
    return clamp_interval(raw,c['MIN_TAU_S'],c['MAX_TAU_S'])
def pseudo_period_from_tau(tau,c):
    if not finite(tau,True):raise ValueError('tau interval must be positive')
    return clamp_interval(I(c['PSEUDO_UPDATE_TAU_RATIO_DEFAULT'])*tau,c['PSEUDO_UPDATE_PERIOD_MIN_S_DEFAULT'],c['PSEUDO_UPDATE_PERIOD_MAX_S_DEFAULT'])
def spectral_mse_rs(tau,sigma_raw,c):
    if not finite(tau,True) or not finite(sigma_raw,True):raise ValueError('positive tau/sigma intervals required')
    if not c['sigma_coeff']>0:raise ValueError('deployed sigma_coeff must be positive')
    ts=pseudo_period_from_tau(tau,c);sigma_aB=sigma_raw/I(c['sigma_coeff']);sigma_aB=Interval(max(1e-6,sigma_aB.lo),max(1e-6,sigma_aB.hi))
    tau2=tau*tau;u=sigma_aB*tau2*tau2;u67=ROOTS.pow_6_7_interval(u);qroot=ROOTS.root_14_interval(I(2*c['R_S_ACCEL_NOISE_DENSITY_DEFAULT']));root_ts=ROOTS.sqrt_interval(ts)
    raw=I(c['R_S_MSE_COEFF_DEFAULT'])*qroot*u67/root_ts
    return clamp_interval(raw,c['MIN_R_S'],c['MAX_R_S'])

@dataclass(frozen=True)
class TargetCell:
    source_token:str;predecessor_token:str|None;frequency_hz:Interval;sigma_target_raw_mps2:Interval;tau_target_s:Interval;pseudo_period_s:Interval;rs_target:Interval

def _dependent_outer_envelopes(dynamic,c):
    inv=dynamic['dynamic_invariant']
    f=Interval(*map(float,inv['tuning_frequency_hz']));s=Interval(*map(float,inv['sigma_target_raw_mps2']))
    tau=tau_from_frequency(f,c);ts=pseudo_period_from_tau(tau,c);rs=spectral_mse_rs(tau,s,c)
    return tau,ts,rs

def make_target_cell(source_token,predecessor_token,frequency_hz,sigma_target_raw_mps2,dynamic):
    if not isinstance(source_token,str) or not source_token:raise ValueError('source token required')
    inv=dynamic['dynamic_invariant']
    if not subset(frequency_hz,inv['tuning_frequency_hz']):raise ValueError('frequency outside dynamic invariant')
    if not subset(sigma_target_raw_mps2,inv['sigma_target_raw_mps2']):raise ValueError('raw sigma target outside dynamic invariant')
    c=constants();tau=tau_from_frequency(frequency_hz,c);ts=pseudo_period_from_tau(tau,c);rs=spectral_mse_rs(tau,sigma_target_raw_mps2,c)
    cell=TargetCell(source_token,predecessor_token,frequency_hz,sigma_target_raw_mps2,tau,ts,rs);failures=validate_target_cell(cell,dynamic)
    if failures:raise ValueError('constructed target cell invalid: '+repr(failures))
    return cell

def validate_target_cell(cell,dynamic):
    f=[];inv=dynamic['dynamic_invariant'];c=constants();tau_outer,ts_outer,rs_outer=_dependent_outer_envelopes(dynamic,c)
    if not isinstance(cell.source_token,str) or not cell.source_token:f.append('missing source token')
    if not finite(cell.frequency_hz,True) or not subset(cell.frequency_hz,inv['tuning_frequency_hz']):f.append('frequency outside invariant')
    if not finite(cell.sigma_target_raw_mps2,True) or not subset(cell.sigma_target_raw_mps2,inv['sigma_target_raw_mps2']):f.append('sigma_target_raw outside invariant')
    # Derived coordinates are checked against the rigorously recomputed image of
    # those source invariants. They are not independent source coordinates.
    for x,o,name in ((cell.tau_target_s,tau_outer,'tau_target'),(cell.pseudo_period_s,ts_outer,'pseudo_period'),(cell.rs_target,rs_outer,'R_S_target')):
        if not finite(x,True) or not interval_subset(x,o):f.append(name+' outside dependent source image')
    for actual,recomputed,name in ((cell.tau_target_s,tau_from_frequency(cell.frequency_hz,c),'tau'),(cell.pseudo_period_s,pseudo_period_from_tau(cell.tau_target_s,c),'T_S'),(cell.rs_target,spectral_mse_rs(cell.tau_target_s,cell.sigma_target_raw_mps2,c),'R_S')):
        if not actual.contains_interval(recomputed):f.append(name+' detached from same-cell map')
    return list(dict.fromkeys(f))

def build(domain_path=DEFAULT_DOMAIN):
    dynamic=DYNAMIC.build(domain_path);df=DYNAMIC.validate(dynamic)
    if df:raise RuntimeError('dynamic source prerequisite failed: '+repr(df))
    rf=ROOTS.validate_self_test()
    if rf:raise RuntimeError('validated-root self test failed: '+repr(rf))
    inv=dynamic['dynamic_invariant']
