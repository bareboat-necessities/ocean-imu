"""Correlated deployed tuner target cell for the complete-BRMM P4 cover.

This remains a coarse sanity/admissibility enclosure only.  The theorem-facing
coefficient family is generated by the same-signal estimator transition.

Given one SAME-SOURCE cell for frequency and raw sigma, construct the dependent
shipping tuple

    (f_tune, tau_target, sigma_target_raw, T_S(tau_target), R_S_target)

without independently selecting tau, T_S or R_S.  Validation of derived
coordinates is against the outward image of the stored frequency/sigma source
enclosure itself, rather than a separately rounded scalar endpoint invariant.
That avoids one-ulp disagreement between two mathematically identical outward
computations without widening the physical shipping clamps.
"""
