"""Joint SAME-SIGNAL WavePeriodEstimator + sigma transition for OU-III P4.

The theorem-facing coordinates are generated by one signal history. This module
does not accept an independent (f,sigma) rectangle. In addition to shipping
first/second EW moments it carries exact ghost central-moment numerators. Those
ghosts are algebraically equivalent to the shipping moments but avoid dependency
loss in interval arithmetic:

    C = q*w - m^2,      variance = C / w^2.

For one EW update m'=r*m+a*x, q'=r*q+a*x^2, w'=r*w+a,

    C' = r^2 C + r*a * (C/w + w*(x-m/w)^2)                  (w>0),

and C'=0 for the first weighted sample. Period and sigma variances are therefore
nonnegative same-history quantities rather than subtraction of detached boxes.

Shipping causality is retained: predecessor usable WPE frequency drives the
current tuner/band update; the current signal sample then updates WPE. A newly
usable current period can affect tuning only on the following sample.
"""
