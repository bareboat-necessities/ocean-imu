def _wave_horizon(period):
    c=WAVE.constants();p=period if period is not None else I(6)
    return clampi(I(c["moment_horizon_periods"])*p,c["min_horizon_sec"],c["max_horizon_sec"])

def _central_update(C,m,w,x,a):
    if C.lo<0:raise ValueError("central numerator lost nonnegativity")
    r=I(1)-a
    if w.hi<=1e-15:return I(0)
    if w.lo<=0:return None
    centered=x-m/w
    return nonnegative(r.square()*C+r*a*(C/w+w*centered.square()))

def _variance_from_central(C,w):
    if C is None or C.lo<0 or w.lo<=1e-12:return None
    return nonnegative(C/w.square())

def _raw_period_from_central(wave,Cv,Ce):
    vv=_variance_from_central(Cv,wave.weight);ev=_variance_from_central(Ce,wave.weight)
    if vv is None or ev is None or ev.lo<=1e-12:return None
    c=WAVE.constants();omega2=vv/ev-c["lambda"].square()
    if omega2.lo<=1e-8:return None
    pi=Interval.outward_bounds(3.141592653589793,3.141592653589794)
    return I(2)*pi/VPOS.sqrt_interval(omega2)

def _canonical_log_step(old_log,raw,dt):
    logr=VPOS.log_interval(raw)
    if old_log is None:return logr
    c=WAVE.constants();k=float(c["log_smoothing_periods"])
    if not k>0:return logr
    old_period=VT.exp_interval(old_log)
    horizon=clampi(I(k)*old_period,max(0.05,dt.lo),35.0)
    alpha=I(1)-VT.exp_interval(-(dt/horizon))
    return old_log+alpha*(logr-old_log)

def _period_from_log(logp):return VT.exp_interval(logp) if logp is not None else None
def _frequency_from_log(logp):return VT.exp_interval(-logp) if logp is not None else None

def _usable(old,w,p):
    if old:return True
    if p is None:return False
    c=WAVE.constants();start=I(3)/c["lambda"];floor=I(4)/c["lambda"]
    return w.elapsed_sec.lo>=floor.hi and (w.elapsed_sec-start).lo>=p.hi

def _band_step(b,x,dt,fref):
    if fref.lo<=0 or dt.lo<=0:return None
    pi=Interval.outward_bounds(3.141592653589793,3.141592653589794)
    nyq=I(.45)/dt;upper=Interval(min(6.,nyq.lo),min(6.,nyq.hi))
    if upper.lo<=.01:return None
    lr=I(.5)*fref;low=Interval(max(.01,lr.lo),max(.01,lr.hi));low=Interval(min(low.lo,upper.lo/1.05),min(low.hi,upper.hi/1.05))
    hr=I(4)*fref;h0=Interval(min(upper.lo,hr.lo),min(upper.hi,hr.hi));h1=Interval(max(h0.lo,1.05*low.lo),max(h0.hi,1.05*low.hi));high=Interval(min(h1.lo,upper.lo),min(h1.hi,upper.hi))
    if high.lo<=low.hi:return None
    al=I(1)-VT.exp_interval(-(I(2)*pi*low*dt));ah=I(1)-VT.exp_interval(-(I(2)*pi*high*dt));ql=I(1)-al;qh=I(1)-ah
    low_new=ql*b.lowpass_low+al*x;band_new=qh*b.band+ah*(ql*(x-b.lowpass_low))
    a00=ql;a10=-(ah*ql);a11=qh;b0=al;b1=ah*ql
    p00=nonnegative(a00.square()*b.p00+b0.square());p01=a00*(a10*b.p00+a11*b.p01)+b0*b1
    p11=nonnegative(a10.square()*b.p00+I(2)*a10*a11*b.p01+a11.square()*b.p11+b1.square())
    return BandState(low_new,band_new,p00,p01,p11,True)

def _tuner_step(t,band,dt,f_input):
    f=clampi(f_input,.05,5.);sea=clampi(I(.5)/f,.5,6.);teff=I(2)*sea;requested=clampi(I(4)*teff,.3,60.);h=clampi(requested,max(.05,dt.lo),35.)
    a=I(1)-VT.exp_interval(-(dt/h));r=I(1)-a
    C=_central_update(t.central_numerator,t.mean_value,t.mean_weight,band,a)
    if C is None:C=I(0)
    mv=r*t.mean_value+a*band;mw=r*t.mean_weight+a;sv=r*t.sq_value+a*band.square();sw=r*t.sq_weight+a
    return TunerState(f,mv,mw,sv,sw,h,C)

def _sigma_raw(t,b,acc_noise_floor_sigma,still_attenuation,sigma_coeff,max_sigma):
    if not(b.ready and acc_noise_floor_sigma.lo>=0 and 0<=still_attenuation.lo<=still_attenuation.hi<=1):return None
    total=_variance_from_central(t.central_numerator,t.mean_weight)
    if total is None:return None
    noise_sigma=acc_noise_floor_sigma*VPOS.sqrt_interval(nonnegative(b.p11))
    wave=nonnegative(total-noise_sigma.square())*still_attenuation;wave=Interval(max(1e-6,wave.lo),max(1e-6,wave.hi))
    return clampi(VPOS.sqrt_interval(wave)*I(sigma_coeff),0.,max_sigma)

def _tuning_input_from_predecessor(s):
    if s.usable_period and s.canonical_log_period is not None:return _frequency_from_log(s.canonical_log_period)
    return prior_frequency()

def _wave_successors(s,dt,input_accel):
    lin=WAVE.linear_frontend_step(s.wave,dt,input_accel);c=WAVE.constants();start=I(3)/c["lambda"]
    if lin.elapsed_sec.hi<start.lo:
        modes=[("pre_moment",lin,s.wave_velocity_central,s.wave_elevation_central)]
    else:
        h=_wave_horizon(s.canonical_period_s);a=WAVE._alpha_for_horizon(dt,h)
        Cv=_central_update(s.wave_velocity_central,lin.velocity_mean,lin.weight,lin.velocity,a)
        Ce=_central_update(s.wave_elevation_central,lin.elevation_mean,lin.weight,lin.elevation,a)
        upd=WAVE.moment_update(lin,dt,h);moment=("moment",upd,Cv,Ce)
        modes=[moment] if lin.elapsed_sec.lo>=start.hi else [("pre_moment",lin,s.wave_velocity_central,s.wave_elevation_central),moment]
    out=[]
    for mode,w,Cv,Ce in modes:
        if Cv is None or Ce is None:
            out.append((w,Cv,Ce,s.canonical_log_period,s.canonical_period_s,s.usable_period,True,"central_weight"));continue
        raw=_raw_period_from_central(w,Cv,Ce) if mode=="moment" else None;logp=s.canonical_log_period
        if raw is not None:logp=_canonical_log_step(logp,raw,dt)
        p=_period_from_log(logp)
        out.append((w,Cv,Ce,logp,p,_usable(s.usable_period,w,p),False,None))
    return out

def step_joint(s,dt,input_accel,*,acc_noise_floor_sigma=None,still_attenuation=None):
    if not s.source_token:raise ValueError("source token required")
    if acc_noise_floor_sigma is None:acc_noise_floor_sigma=deployed_acc_noise_floor_sigma()
    if still_attenuation is None:still_attenuation=I(1.0)
    tc=TARGET.constants();f_tuner=_tuning_input_from_predecessor(s)
    f_band=s.tuner.frequency_hz if s.tuner.frequency_hz is not None else f_tuner;f_band=clampi(f_band,tc["MIN_TUNE_FREQ_HZ"],tc["MAX_TUNE_FREQ_HZ"])
    band=_band_step(s.band,input_accel,dt,f_band)
    if band is None:return [JointImage(s,"split_required_band_coefficients",None,None,None,None,None)]
    tuner=_tuner_step(s.tuner,band.band,dt,f_tuner);sig=_sigma_raw(tuner,band,acc_noise_floor_sigma,still_attenuation,tc["sigma_coeff"],tc["MAX_SIGMA_A"])
    tau=TARGET.tau_from_frequency(f_tuner,tc) if sig is not None else None;ts=TARGET.pseudo_period_from_tau(tau,tc) if tau is not None else None;rs=TARGET.spectral_mse_rs(tau,sig,tc) if tau is not None and sig is not None else None
    out=[]
    for w,Cv,Ce,logp,period,usable,split,reason in _wave_successors(s,dt,input_accel):
        ns=JointEstimatorState(s.source_token,s.source_token,w,period,usable,band,tuner,Cv or I(0),Ce or I(0),logp)
        if split:out.append(JointImage(ns,"split_required_"+str(reason),f_tuner,sig,tau,ts,rs))
