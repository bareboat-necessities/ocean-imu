#!/usr/bin/env python3
"""Exact/outward nonlinear prediction Jacobian for complete-BRMM OU-III P4.

The prediction is differentiated from SAME-source shipping coordinates; no
independent F box is accepted.  Inputs are the source-derived nominal
bias-corrected body rate ``omega_hat``, sample interval ``h`` and committed
``tau_aw``.  The translational [v,p,S,a_w] transition is generated by the exact
shipping integrated-OU primitive.  In A21 the active accelerometer-bias mean
uses the configured exact Gauss--Markov factor.

For left attitude error E=R_true R_hat^T and gyro-bias error db_g, both true and
nominal estimators see the same gyro sample, hence

    omega_true_est = omega_hat - db_g,

and the exact relative prediction is

    E+ = Rstep(-(omega_hat-db_g) h) E Rstep(-omega_hat h)^T.

``Rstep`` is built through the same deployed ``quat_from_delta_theta`` branch
that shipping uses and then represented in exact Cayley coordinates.  No
small-angle reset approximation is introduced.  The other state means obey

    db_g+ = db_g,
    [dv,dp,dS,da_w]+ = F_LL(tau_aw,h)[dv,dp,dS,da_w],
    db_a+ = phi_ba db_a  (A21).

At zero error the full Jacobian encloses the literal shipping prediction F,
including the exact attitude/gyro-bias cross block and every v/p/S/a_w row.
The process Q remains in the same source Riccati history used by the pullback
metric; it is not part of the deterministic state Jacobian and is never
removed from the complete word.

The evaluator also returns the outward finite ``state_out`` from the very same
AD composition.  This is used by non-promoting physical finite-map feasibility
and later mean-value enclosure; it does not introduce a second predictor.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Sequence

from ou3_interval import Interval
import ou3_interval_ad as AD
import ou3_brmm_complete_source as COMPLETE
import ou3_brmm_shipping_prediction_primitives as SHIPPING
import ou3_validated_transcendentals as VT

REPO = Path(__file__).resolve().parents[2]
DEFAULT_DOMAIN = REPO / "tools" / "stability" / "ou3_proof_operating_domain.json"
SCHEMA = 1
QUALIFICATION = "OU3_P4_COMPLETE_BRMM_NONLINEAR_PREDICTION_DIFFERENTIAL_V1"

OFF_BG = 3
OFF_V = 6
OFF_BA = 18


def _dim(mode: str) -> int:
    if mode == "H": return 18
    if mode == "A": return 21
    raise ValueError("prediction differential mode must be H or A")


def _shape(A) -> tuple[int, int]:
    r = len(A); c = len(A[0]) if r else 0
    if any(len(row) != c for row in A):
        raise ValueError("ragged matrix")
    return r, c


def _transpose(A):
    return [[A[i][j] for i in range(len(A))] for j in range(len(A[0]))]


def _deployed_step_rotation(d):
    """AD rotation matrix of shipping quat_from_delta_theta(d); normalization cancels in Cayley."""
    w, v, _ = AD.deployed_quaternion_ad(d)
    two = AD.constant(2.0, d[0].n)
    a = [two * x / w for x in v]
    return AD.rotation_from_cayley(a)


def _rotation_matrix_to_cayley(R):
    n = R[0][0].n
    one = AD.constant(1.0, n)
    two = AD.constant(2.0, n)
    den = one + R[0][0] + R[1][1] + R[2][2]
    if den.val.lo <= 0.0:
        raise RuntimeError("predicted relative attitude can leave finite Cayley chart")
    vee = [
        R[2][1] - R[1][2],
        R[0][2] - R[2][0],
        R[1][0] - R[0][1],
    ]
    return [two * x / den for x in vee]


def _translation_F(tau_aw: Interval, h: Interval):
    axis = SHIPPING.translation_axis_transition(tau_aw, h)
    z = Interval.point(0.0)
    F = [[z for _ in range(12)] for _ in range(12)]
    idx = (0, 3, 6, 9)
    for a in range(3):
        for i in range(4):
            for j in range(4):
                F[idx[i] + a][idx[j] + a] = axis[i][j]
    return F


def prediction_event(
    mode: str,
    state: Sequence[Interval],
    omega_hat: Sequence[Interval],
    h: Interval,
    tau_aw: Interval,
    *,
    tau_ba: Interval | None = None,
):
    """Return same-source finite state, F_LL/phi_ba and outward state Jacobian."""
    n = _dim(mode)
    if len(state) != n or len(omega_hat) != 3:
        raise ValueError("prediction state/body-rate dimension mismatch")
    if any(not isinstance(x, Interval) for x in [*state, *omega_hat, h, tau_aw]):
        raise TypeError("prediction differential requires outward Interval source cells")
    if h.lo <= 0.0 or tau_aw.lo <= 0.0:
        raise ValueError("positive source h/tau_aw required")
    if mode == "A" and (tau_ba is None or tau_ba.lo <= 0.0):
        raise ValueError("A21 prediction requires positive configured tau_ba")

    z = AD.independent_vector(state, n=n, offset=0)
    E = AD.rotation_from_cayley(z[:3])
    dbg = z[OFF_BG:OFF_BG + 3]
    d_shadow = [(-AD.constant(omega_hat[i], n) + dbg[i]) * AD.constant(h, n) for i in range(3)]
    d_nom = [-AD.constant(omega_hat[i], n) * AD.constant(h, n) for i in range(3)]
    Rs = _deployed_step_rotation(d_shadow)
    Rn = _deployed_step_rotation(d_nom)
    Eplus = AD.matmul(AD.matmul(Rs, E), _transpose(Rn))
    cplus = _rotation_matrix_to_cayley(Eplus)

    out = list(cplus)
    out.extend(dbg)  # gyro-bias homogeneous mean is constant

    Fll = _translation_F(tau_aw, h)
    xlin = z[OFF_V:OFF_V + 12]
    xlin_plus = []
    for i in range(12):
        s = AD.constant(0.0, n)
        for j in range(12):
            s = s + AD.constant(Fll[i][j], n) * xlin[j]
        xlin_plus.append(s)
    out.extend(xlin_plus)

    phi_ba = None
    if mode == "A":
        phi_ba = VT.exp_interval(-(h / tau_ba))
        out.extend(AD.constant(phi_ba, n) * z[OFF_BA + i] for i in range(3))

    if len(out) != n:
        raise RuntimeError("prediction differential output dimension drifted")
    return {
        "state_out": AD.values(out),
        "J_state": AD.jacobian(out),
        "F_LL": Fll,
        "phi_ba": phi_ba,
        "same_source_omega_h_tau": True,
        "full_F_Eaw_translation_rows_retained": True,
    }


def build(domain_path: Path = DEFAULT_DOMAIN) -> dict:
    path = Path(domain_path).resolve()
    source = COMPLETE.build(path)
    shipping = SHIPPING.build()
    failures = (
        [f"source: {x}" for x in COMPLETE.validate(source)]
        + [f"shipping prediction: {x}" for x in SHIPPING.validate(shipping)]
    )
    if failures:
        raise RuntimeError(f"prediction differential prerequisites failed: {failures}")
    live = json.loads(path.read_text(encoding="utf-8"))["normal_live"]
    return {
        "schema": SCHEMA,
        "qualification": QUALIFICATION,
        "canonical_source": "COMPLETE_BRMM_NORMAL_LIVE_WORD",
        "same_complete_BRMM_omega_h_tau_required": True,
        "independent_F_input_allowed_for_theorem": False,
        "exact_relative_attitude_prediction_differentiated": True,
        "finite_physical_state_output_available": True,
        "finite_state_and_Jacobian_share_one_AD_composition": True,
        "shipping_deployed_quaternion_branch_used": True,
        "integrated_OU_F_LL_generated_from_same_committed_tau": True,
        "full_F_Eaw_v_p_S_aw_rows_retained": True,
        "gyro_bias_homogeneous_mean_constant": True,
        "A21_accelerometer_bias_GM_mean_retained": True,
        "process_Q_remains_in_same_source_Riccati_metric": True,
        "body_rate_norm_upper_deg_s_from_source": float(live["body_rate_norm_upper_deg_s"]),
        "packetwise_norm_sum_used": False,
        "trajectory_replay_used": False,
        "source_family_replaced": False,
        "filter_changed": False,
        "declared_domain_changed": False,
        "source_uniform_prediction_Jacobian_closed": False,
        "P4_promoted_here": False,
        "next_obligation": (
            "feed the same complete-BRMM omega/tau sample cells into this exact predictor, validate zero-error parity with shipping F, and compose with same-cell Joseph Jacobians without forming independent per-sample boxes"
        ),
    }


def validate(d: dict) -> list[str]:
    f: list[str] = []
    if d.get("schema") != SCHEMA or d.get("qualification") != QUALIFICATION:
        f.append("schema/qualification mismatch")
    if d.get("canonical_source") != "COMPLETE_BRMM_NORMAL_LIVE_WORD":
        f.append("canonical source changed")
    for key in (
        "same_complete_BRMM_omega_h_tau_required", "exact_relative_attitude_prediction_differentiated",
        "finite_physical_state_output_available", "finite_state_and_Jacobian_share_one_AD_composition",
        "shipping_deployed_quaternion_branch_used", "integrated_OU_F_LL_generated_from_same_committed_tau",
        "full_F_Eaw_v_p_S_aw_rows_retained", "gyro_bias_homogeneous_mean_constant",
        "A21_accelerometer_bias_GM_mean_retained", "process_Q_remains_in_same_source_Riccati_metric",
    ):
        if d.get(key) is not True:
            f.append(f"{key} is not true")
    for key in (
        "independent_F_input_allowed_for_theorem", "packetwise_norm_sum_used", "trajectory_replay_used",
        "source_family_replaced", "filter_changed", "declared_domain_changed",
        "source_uniform_prediction_Jacobian_closed", "P4_promoted_here",
    ):
        if d.get(key) is not False:
            f.append(f"{key} is not false")
    if not float(d.get("body_rate_norm_upper_deg_s_from_source", 0.0)) > 0.0:
        f.append("source body-rate cap lost")
    return list(dict.fromkeys(f))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--domain", type=Path, default=DEFAULT_DOMAIN)
    ap.add_argument("--output", type=Path, required=True)
    args = ap.parse_args()
    d = build(args.domain)
    failures = validate(d)
    d["validation_pass"] = not failures
    d["validation_failures"] = failures
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(d, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps({
        "source": d["canonical_source"],
        "exact_attitude_prediction": d["exact_relative_attitude_prediction_differentiated"],
        "finite_state_output": d["finite_physical_state_output_available"],
        "full_F_Eaw": d["full_F_Eaw_v_p_S_aw_rows_retained"],
        "prediction_Jacobian_closed": d["source_uniform_prediction_Jacobian_closed"],
        "failures": failures,
    }, indent=2, sort_keys=True))
    return 0 if not failures else 2


if __name__ == "__main__":
    raise SystemExit(main())
