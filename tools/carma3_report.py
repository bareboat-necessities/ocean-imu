def load_trace(path):
    with path.open() as f:
        r = csv.reader(f)
        hdr = next(r)
        data = np.array([[float(x) if x not in ("", "nan") else np.nan for x in row] for row in r])
    return {h: data[:, i] for i, h in enumerate(hdr)}


