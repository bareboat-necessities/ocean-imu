#!/usr/bin/env python3
"""Render reviewed per-record evidence; never refit limits from a failing run."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
METRICS = ('heave', 'displacement', 'roll', 'pitch', 'yaw', 'acc_z', 'acc_3d', 'gyro_3d')


def render(evidence):
    rows = []
    for entry in evidence['entries']:
        values = ', '.join(f"{entry['limits'].get(k, 0):.5f}f" for k in METRICS)
        rows.append('    {"%s", "%s", "%s", {%s}},' %
                    (entry['family'], entry['profile'], entry['input'], values))
    return ('// Generated by tools/generate_record_replay_limits.py. Do not edit.\n'
            '// Per-sea caps from per_record_limits.json; metric order is Metric.\n'
            'inline constexpr Entry entries[] = {\n' + '\n'.join(rows) + '\n};\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = json.loads((ROOT / 'reports/results/filter_sim_gates/per_record_limits.json').read_text())
    target = ROOT / 'tests/common/RecordReplayLimits.inc'
    expected = render(data)
    if args.check:
        if target.read_text() != expected:
            raise SystemExit('per-record C++ limits differ from reviewed evidence')
    else:
        target.write_text(expected)


if __name__ == '__main__':
    main()
