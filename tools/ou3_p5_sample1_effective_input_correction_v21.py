"""V21: source-correlated effective-input correction audit at the first q8 witness.

V20 proves that a first-residual-row direction audit is useful for many source
rows, but the actual first V18B/V19 q8 witness (p=0,tangent=0,axial=19) admits
all startup Cayley direction boxes.  The missing dependency is later: V13E
constructs the sample-1 correction from a norm-only residual ball, while the
current Cayley state and that correction are generated by the same
accelerometer residual.

In V7's un-Rx proof gauge the nominal sample-1 force is f=[0,f_y,f_z] and the
shipping attitude Jacobian is H_theta=-[f]_x.  For current Cayley vector c,

    H_theta c = [ f_z c_y-f_y c_z, -f_z c_x, f_y c_x ].

The exact effective-vector-input lemma already certified in P5 rewrites the
finite-angle accelerometer defect into the a_w coordinate.  Thus the nominal
sample-1 residual can be enclosed as

    r = H_theta c + n,

where n contains the physical a_w error, accelerometer-bias error, exact
finite-angle attitude defect, and rotated latent-error cross term.  V7's exact
one-plus-two attitude gain then gives a source-correlated correction box:

    d_x  = K_xy r_y + K_xz r_z,
    d_yz = [g_y,g_z] r_x.

V21 builds this box from the V18B current component chart and intersects it with
the historical V13E signed correction subcell at the first q8 witness.  The
existing V12D PSD/S residual and gain perturbations are retained unchanged as
an additive correction ball.  It then asks whether the refined correction
closes q<8 by either the existing SO(3) geodesic route or the signed-product
current-y/z support route.

This is a focused diagnostic only.  It does not promote sample 1, a complete
word, or N_H_words, and it changes no estimator, source domain, six-radian
shipping correction limit, or q<8 target.
"""
