def validate(d: dict) -> list[str]:
    f = list(d.get("failures", []))
    if d.get("schema") != SCHEMA:
        f.append("schema mismatch")
    if d.get("qualification") != "OU3_P5_SAMPLE1_EFFECTIVE_INPUT_CORRECTION_WITNESS_V21":
        f.append("qualification mismatch")
    for key in (
        "source_generated_not_trajectory_fit", "V12D_PSD_S_perturbation_retained",
        "V10_one_plus_two_gain_retained", "exact_accelerometer_effective_input_lemma_used",
        "current_cayley_and_sample1_correction_jointly_mapped",
        "V13E_signed_subcell_intersected_not_replaced",
    ):
        if d.get(key) is not True:
            f.append(f"{key} is not true")
    for key in (
        "source_replay_used", "filter_changed", "deployed_correction_limit_increased",
        "q8_composed_here", "q8_word_promoted_here", "whole_word_promoted_here",
        "N_H_words_set_here",
    ):
        if d.get(key) is not False:
            f.append(f"{key} is not false")
    if float(d.get("deployed_correction_limit_rad", 0.0)) != 6.0:
        f.append("deployed correction limit changed")
    if float(d.get("q_target", 0.0)) != Q_TARGET:
        f.append("q target changed")
    for key in (
        "sample1_current_cayley_norm_upper",
        "nominal_effective_residual_nuisance_norm_upper_mps2",
        "V12D_correction_perturbation_norm_upper_rad",
        "baseline_correction_radial_upper_rad",
        "refined_correction_radial_upper_rad",
    ):
        x = d.get(key)
        if not isinstance(x, (int, float)) or not math.isfinite(float(x)) or float(x) < 0.0:
            f.append(f"invalid {key}")
    if (not d.get("source_subcell_incompatible")
            and float(d.get("refined_correction_radial_upper_rad", math.inf))
            > float(d.get("baseline_correction_radial_upper_rad", -math.inf))):
        f.append("source intersection worsened correction radial upper")
    st = d.get("P5_SAMPLE1_EFFECTIVE_INPUT_CORRECTION_WITNESS_V21")
    if st not in ("PASS", "NOT_ESTABLISHED"):
        f.append("invalid V21 status")
    if st == "PASS" and d.get("joint_correction_box_rad") is None \
            and d.get("source_subcell_incompatible") is not True:
        f.append("V21 PASS lost joint correction box without proving incompatibility")
    return list(dict.fromkeys(f))


