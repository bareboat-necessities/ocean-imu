#!/usr/bin/env python3
"""Publish both complete v1.4.0 reports; historical controls keep their own pins."""
import argparse
import csv
import json
from pathlib import Path

from sim_dataset import ROOT, RELEASE, CASES, REFERENCE_CSV_SHA256_BY_CASE
from sim_matrix import metric_rows

LABELS = {'ou2':'OU-II', 'ou3':'OU-III', 'tfg':'TFG', 'tfg_legacy':'TFG cubic',
          'carma':'CARMA', 'csm':'Shared QMEKF', 'tcarma':'TFG-CARMA', 'tcsm':'Shared TFG',
          'tangent':'Shared tangent', 'ahrs':'AHRS', 'pii':'Adaptive PII', 'nlo':'TVG-NLO',
          'heave_pii':'Heave PII', 'heave_godhavn':'Godhavn', 'heave_godhavn_ext':'Godhavn extended',
          'heave_richter_zd':'Richter', 'heave_kuchler':'Kuchler'}
DOCS = ('kalman_ou_iii', 'kalman_tfg', 'kalman_carma', 'kalman_carma_shared_modes',
        'kalman_tfg_carma', 'kalman_tfg_shared_modes')


def publish(root):
    prose = (f'The current external-data baseline uses oceanography-waves-lib {RELEASE}: '
             'a 28 ft estimated hull RAO at 5 kn, following seas northbound and head/bow-quartering '
             'seas southbound, both with a ±3° heading sine every 20 s. Each case contains eight '
             '1200 s, 200 Hz records. The final 900 s are scored, except AHRS attitude (final 60 s). '
             'Displacement and velocity truth are relative to the declared cruise track; total '
             'acceleration and delivered IMU samples are retained. These are deterministic '
             'regression measurements, not confidence intervals or sea trials.')
    md = ['# Underway replay results', '', prose, '']
    tex = [r'% Generated by tools/moving_vessel_publication.py.',
           r'\section{Current Underway Replay Baseline}',
           prose.replace('±3°', r'$\pm3^\circ$'), '']
    summary = []
    for case, spec in CASES.items():
        report = json.loads((root/case/'measurements.json').read_text())
        if (report.get('case') != case or report['inputs']['release'] != RELEASE or
                report['inputs']['archive_sha256'] != spec['sha256'] or
                report['inputs']['input_sha256'] != REFERENCE_CSV_SHA256_BY_CASE[case]):
            raise ValueError(f'{case}: publication inputs differ from the pinned case')
        if (report.get('acceptance') != 'all replay gates passed' or
                any(code for profiles in report['replay_exit_codes'].values() for code in profiles.values())):
            raise ValueError(f'{case}: publication requires a complete passing replay')
        rows = metric_rows(report)
        if len(rows) != 272:
            raise ValueError(f'{case}: incomplete replay inventory')
        md += [f'## {spec["description"].capitalize()}', '',
               '| Filter | JONSWAP heave (% Hs) | PM-Stokes heave (% Hs) | 3D RMS (m) | Yaw RMS (deg) |',
               '| --- | ---: | ---: | ---: | ---: |']
        tex += [r'\paragraph{'+spec['description'].capitalize()+'}',
                r'\begin{center}\small\setlength{\tabcolsep}{4pt}\begin{tabular}{lrrrr}',
                r'\hline Filter & JONSWAP & PM--Stokes & 3-D & Yaw \\',
                r' & \%$H_s$ & \%$H_s$ & m & deg \\ \hline']
        for family, label in LABELS.items():
            selected = [r for r in rows if r['family']==family and r['profile']=='default']
            if len(selected) != 8:
                raise ValueError(f'{case}/{family}: missing production records')
            def worst(key, wave='', selected=selected):
                values = [r[key] for r in selected if key in r and wave in r['input']]
                return max(values) if values else None
            record = dict(case=case, filter=label,
                          heave_jonswap_pct_hs=worst('disp_z_pct_hs','jonswap'),
                          heave_pmstokes_pct_hs=worst('disp_z_pct_hs','pmstokes'),
                          disp_3d_rms_m=worst('disp_3d_rms_m'), yaw_rms_deg=worst('yaw_rms_deg'))
            summary.append(record)
            values = [f'{value:.3f}' if value is not None else '—' for value in list(record.values())[2:]]
            md.append('| '+' | '.join([label,*values])+' |')
            tex.append(' & '.join([label,*[v.replace('—','--') for v in values]])+r' \\')
        md += ['', f'[Full metrics](../reports/results/sim_v1.4.0/{case}/metrics.csv) · '
                   f'[Charts and provenance](../reports/results/sim_v1.4.0/{case}/README.md)', '']
        tex += [r'\hline\end{tabular}\end{center}', '']
    note = ('Each column is the worst of eight records; maxima need not occur together. '
            'Each case/sea/profile has its own fixed limit. All profiles, roll/pitch, bias '
            'metrics and input/executable hashes remain in the case-specific JSON/CSV reports.')
    md += [note, '', 'See [the scoring convention](moving-vessel-replays.md) and '
           '[gate protocol](filter-simulator-gates.md).', '']
    tex += [note.replace('case-specific JSON/CSV reports', r'\path{reports/results/sim_v1.4.0} reports'), '']
    (ROOT/'docs/moving-vessel-results.md').write_text('\n'.join(md))
    for directory in DOCS:
        (ROOT/'doc'/directory/'underway-baseline.tex-part').write_text('\n'.join(tex))
    with (root/'summary.csv').open('w') as stream:
        writer = csv.DictWriter(stream,fieldnames=summary[0],lineterminator='\n')
        writer.writeheader()
        writer.writerows(summary)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--results', type=Path, default=ROOT/'reports/results/sim_v1.4.0')
    publish(parser.parse_args().results)
