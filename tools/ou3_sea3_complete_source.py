    G_range = list(map(float, rbox["peak_translation_gain"]))
    fc_range = list(map(float, rbox["rolloff_corner_hz"]))
    pmin = float(rbox["high_frequency_rolloff_power_min"])
    hs_upper = float(physical["repository_total_Hs_upper_m"])

    # The independent worst corner is retained only as a rejection diagnostic.
    cartesian_acc = _accel_covariance_upper(hs_upper, G_range[1], fc_range[1])
    cartesian_acc_pass = cartesian_acc <= acc_trace_threshold

    rs_parity = _source_rs_parity()
    rs_failures = [k for k, ok in rs_parity.items() if not ok]

    sea = moment["sea_family"]
    directional = json.loads(response_domain_path.read_text(encoding="utf-8"))[
        "directional_spectrum_contract"
    ]

