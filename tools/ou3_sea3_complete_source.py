def _exp_minus_integer(t: int) -> Interval:
    if not isinstance(t, int) or isinstance(t, bool) or t < 0:
        raise ValueError("tail exponent must be a nonnegative integer")
    base = VT.exp_point(-0.5)
    out = Interval.point(1.0)
    for _ in range(2 * t):
        out = out * base
    return out


def _select_tail_exponent(samples: int, budget: float) -> dict:
    if samples <= 0:
        raise ValueError("samples must be positive")
    blo = down(float(budget))
    for t in range(1, 257):
        e = _exp_minus_integer(t)
        prob = up(float(2 * DIM * samples) * e.hi)
        if prob <= blo:
            return {
                "integer_tail_exponent": t,
                "validated_exp_minus_t": e.as_list(),
                "failure_probability_upper": prob,
                "allocated_budget_lower": blo,
            }
    raise RuntimeError("finite-horizon SEA3 concentration exponent exceeded 256")


def _trace_threshold(cap: float, t: int) -> float:
    cap2 = down(float(cap) * float(cap))
    return down(cap2 / float(2 * DIM * t))


def _accel_covariance_upper(hs: float, gain: float, corner: float) -> float:
    # tr Cov[a] <= pi^4 Hs^2 G^2 fc^4, all factors outward enclosed.
    pi = Interval.outward_bounds(math.pi, math.pi)
    H = Interval.outward_bounds(hs, hs)
    G = Interval.outward_bounds(gain, gain)
    fc = Interval.outward_bounds(corner, corner)
    return (pi.square() * pi.square() * H.square() * G.square() * fc.square() * fc.square()).hi


def _body_rate_covariance_upper(hs: float, gain_rad_per_m: float, corner: float) -> float:
    H = Interval.outward_bounds(hs, hs)
    K = Interval.outward_bounds(gain_rad_per_m, gain_rad_per_m)
    fc = Interval.outward_bounds(corner, corner)
    return (Interval.point(DEGREE_COEFF) * H.square() * K.square() * fc.square()).hi


