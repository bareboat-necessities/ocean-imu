#!/usr/bin/env python3
"""Explicitly initialize a reviewed dataset baseline; never called by CI.

Normal regression commands only read the locked limits. Rerunning this command
is a deliberate gate change and its evidence diff must be reviewed like code.
"""
import argparse
import json
import math
from pathlib import Path

from sim_dataset import ROOT, CASES, RELEASE, REFERENCE_CSV_SHA256_BY_CASE, digest
from sim_matrix import metric_rows
from filter_sim_gates import REPLAYS, measured_worst
from generate_record_replay_limits import render

MAP = dict(heave='disp_z_pct_hs', displacement='disp_3d_pct_refmax', roll='roll_rms_deg',
           pitch='pitch_rms_deg', yaw='yaw_rms_deg', acc_z='acc_bias_z_percent',
           acc_3d='acc_bias_3d_percent', gyro_3d='gyro_bias_3d_percent')


def cap(value):
    if not math.isfinite(value) or value < 0:
        raise ValueError(f'invalid RMS {value}')
    return round(max(1e-5, math.ceil(value * 1.005 / 1e-5) * 1e-5), 5)


def make_baseline(reports):
    entries, inputs = [], {}
    family_rows = {}
    for case in CASES:
        report = reports[case]
        expected = REFERENCE_CSV_SHA256_BY_CASE[case]
        if report['inputs']['case'] != case or report['inputs']['release'] != RELEASE:
            raise ValueError('case/release mismatch')
        if report['inputs']['input_sha256'] != expected:
            raise ValueError('wrong input bytes')
        if set(report['binary_sha256']) != set(REPLAYS):
            raise ValueError('incomplete filter inventory')
        if any(code not in (0, 1) for profiles in report['replay_exit_codes'].values() for code in profiles.values()):
            raise ValueError('cannot initialize limits from a crashed replay')
        inputs[case] = report['inputs']
        rows = metric_rows(report)
        for row in rows:
            profile = row['profile']
            if row['family'].startswith('heave_') and profile == 'default':
                profile = 'mahony'
            values = {metric: float(row[key]) for metric, key in MAP.items() if key in row}
            if row['family'] == 'pii':
                values = {k: v for k,v in values.items() if k in ('heave', 'yaw')}
            entries.append(dict(case=case, family=row['family'], profile=profile, input=row['input'],
                                measured_max=values, limits={key: cap(value) for key,value in values.items()}))
        for family, profiles in report['records'].items():
            for profile, records in profiles.items():
                family_rows.setdefault(family, {}).setdefault(profile, []).extend(records)
    entries.sort(key=lambda e: (e['case'], e['family'], e['profile'], e['input']))
    # Reject omissions and duplicates independently of the measured report's inventory.
    keys = {(e['case'],e['family'],e['profile'],e['input']) for e in entries}
    if len(keys) != 544 or len(entries) != 544:
        raise ValueError(f'expected 544 distinct filter/profile/sea/case cells, got {len(keys)}')
    for case in CASES:
        other = 'head' if case == 'following' else 'following'
        if reports[case]['binary_sha256'] != reports[other]['binary_sha256']:
            raise ValueError('directions must be evaluated with identical binaries')
    evidence = dict(release=RELEASE, margin_fraction=.005, rounding=1e-5,
                    protocol='full 1200 s, 200 Hz records; final 900 s (AHRS final 60 s); default noise/seeds',
                    inputs=inputs, entries=entries,
                    note='New dataset baseline: both v1.4.0 directions and 20 s steering. '
                         'Old v1.3.1 numeric caps are not comparable controls. CI never refits these limits.')
    families = {}
    for family, profiles in sorted(family_rows.items()):
        families[family] = {}
        for profile, rows in profiles.items():
            worst = measured_worst(rows)
            prefix = 'current' if profile == 'default' else 'interval'
            families[family][prefix+'_limits'] = {key: cap(value) for key,value in worst.items()}
            families[family][prefix+'_measured_worst'] = worst
    return evidence, dict(release=RELEASE, inputs=inputs, families=families)


def render_global(data):
    text = ('#pragma once\n// Generated by tools/lock_simulation_baseline.py.\n'
            '// Global ceilings across BOTH v1.4.0 cases; RecordReplayLimits tightens\n'
            '// every default-seed channel to its own case/profile/sea measurement.\n'
            '#include "util/W3dSimCommon.h"\nnamespace ocean_imu::sim::current_limits {\n')
    for profile in ('current', 'interval'):
        if profile == 'interval': text += '\nnamespace interval {\n'
        for family, rows in data['families'].items():
            limits = rows.get(profile+'_limits')
            if not limits: continue
            text += f'\ninline constexpr W3dFailureLimits {family}{{\n'
            text += ''.join(f'    .{key} = {value:.5f}f,\n' for key,value in limits.items())
            text += '};\n'
        if profile == 'interval': text += '} // namespace interval\n'
    return text + '} // namespace ocean_imu::sim::current_limits\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--measurements', type=Path, default=ROOT/'reports/results/sim_v1.4.0')
    parser.add_argument('--write-reviewed-baseline', action='store_true', required=True)
    args = parser.parse_args()
    paths = {c: args.measurements/c/'measurements.json' for c in CASES}
    reports = {c: json.loads(p.read_text()) for c,p in paths.items()}
    evidence, global_caps = make_baseline(reports)
    evidence['measurement_sha256'] = {c:digest(p) for c,p in paths.items()}
    out = ROOT/'reports/results/filter_sim_gates'
    (out/'per_record_limits.json').write_text(json.dumps(evidence,indent=2,allow_nan=False)+'\n')
    (out/'limits.json').write_text(json.dumps(global_caps,indent=2,allow_nan=False)+'\n')
    (ROOT/'tests/common/RecordReplayLimits.inc').write_text(render(evidence))
    (ROOT/'tests/common/CurrentReplayLimits.h').write_text(render_global(global_caps))


if __name__ == '__main__':
    main()
