#!/usr/bin/env python3
"""Validated algebraic backend for the canonical OU-III SEA3 P3 word.

This module is *not* a reduced P3 route.  It implements the exact full-matrix
bookkeeping required by the canonical proof for one already-enclosed source/
event word.  The word assembler must supply the actual interval F, Q, H, R and
PSD covariance-floor increments generated by the complete Normal-Live source.

The backend propagates three matrices on the same event sequence:

    P_k = Psi_k P_0 Psi_k^T + Omega_k.

Prediction:

    P-     = F P F^T + Q
    Psi-   = F Psi
    Omega- = F Omega F^T + Q

Joseph measurement correction:

    S  = H P- H^T + R
    K  = P- H^T S^-1
    A  = I - K H
    P+     = A P- A^T + K R K^T
    Psi+   = A Psi-
    Omega+ = A Omega- A^T + K R K^T

A shipping PSD a_w covariance-floor event adds the same embedded Delta to P and
Omega and leaves Psi unchanged.

The only theorem-level contraction test exposed here is

    Omega_W - delta P_W >= 0,

checked by outward interval LDL^T on the complete H18/A21 matrix.  No D_W/L_W
split, one-step process ratio, determinant/trace scalarization, or blockwise
minimum can pass through this backend.
"""
from __future__ import annotations

from dataclasses import dataclass
import math
from pathlib import Path
from typing import Sequence

from ou3_interval import (
    Interval,
    IntervalMatrix,
    matrix_add,
    matrix_identity,
    matrix_mul,
    matrix_point,
    matrix_sub,
    matrix_transpose,
    symmetric_positive_definite_ldlt,
)
from ou3_interval_linear_algebra import (
    matrix_inverse_gauss_jordan,
    matrix_symmetric_hull,
)

REPO = Path(__file__).resolve().parents[1]
MEKF = REPO / "src" / "kalman_ou_iii" / "Kalman3D_Wave_OU_III.h"
USEFUL_GATE = 1.0e-18


def _shape(A: Sequence[Sequence[Interval]]) -> tuple[int, int]:
    rows = len(A)
    cols = len(A[0]) if rows else 0
    if any(len(row) != cols for row in A):
        raise ValueError("ragged interval matrix")
    return rows, cols


def _zero(rows: int, cols: int) -> IntervalMatrix:
    z = Interval.point(0.0)
    return [[z for _ in range(cols)] for _ in range(rows)]


def _scale(A: Sequence[Sequence[Interval]], c: float) -> IntervalMatrix:
    ci = Interval.outward_bounds(float(c), float(c))
    return [[ci * A[i][j] for j in range(len(A[i]))] for i in range(len(A))]


def _contains_zero(A: Sequence[Sequence[Interval]]) -> bool:
    return all(x.lo <= 0.0 <= x.hi for row in A for x in row)


def _copy(A: Sequence[Sequence[Interval]]) -> IntervalMatrix:
    return [[x for x in row] for row in A]


def shipping_source_parity() -> dict[str, bool]:
    """Bind the algebraic event recursions to the retained shipping source."""
    text = MEKF.read_text(encoding="utf-8")
    return {
        "prediction_adds_attitude_process_Q": (
            "Pext.template block<NA,NA>(0,0).noalias() += Q_AA;" in text
        ),
        "prediction_adds_translation_process_Q": (
            "T sum = Q_LL(i,j);" in text
        ),
        "active_bias_exact_GM_process_present": (
            "const T qd_scale = -T(0.5) * tau_b * std::expm1(-T(2) * Ts / tau_b);" in text
            and "P_BB.noalias() += Q_bacc_ * qd_scale;" in text
        ),
        "pending_aw_floor_applied_before_S_due_check": (
            text.find("apply_pending_aw_covariance_inflation_();") >= 0
            and text.find("applyIntegralZeroPseudoMeas();", text.find("apply_pending_aw_covariance_inflation_();"))
            > text.find("apply_pending_aw_covariance_inflation_();")
        ),
        "aw_floor_is_PSD_addition": (
            "Pext.template block<3,3>(OFF_AW, OFF_AW) += Delta;" in text
        ),
        "accelerometer_uses_full_Joseph_update": (
            "joseph_update3_(K, S_mat, PCt);" in text
        ),
        "S_zero_update_uses_full_Joseph_update": (
            text.count("joseph_update3_(K, S_mat, PCt);") >= 2
        ),
        "magnetometer_covariance_update_is_Joseph_form": (
            "Pext(i,j) += delta;" in text and "KSK_ij += Kia * S(a,b) * Kjb;" in text
        ),
    }


@dataclass
class JointWordState:
    P0: IntervalMatrix
    P: IntervalMatrix
    Psi: IntervalMatrix
    Omega: IntervalMatrix
    events: int = 0
    predictions: int = 0
    measurements: int = 0
    floors: int = 0

    @property
    def dimension(self) -> int:
        return len(self.P)


def initialize(P0: Sequence[Sequence[Interval]]) -> JointWordState:
    n, m = _shape(P0)
    if n == 0 or n != m:
        raise ValueError("P0 must be nonempty square")
    P0s = matrix_symmetric_hull(_copy(P0))
    return JointWordState(
        P0=P0s,
        P=_copy(P0s),
        Psi=matrix_identity(n),
        Omega=_zero(n, n),
    )


def decomposition_residual(state: JointWordState) -> IntervalMatrix:
    rhs = matrix_add(
        matrix_mul(matrix_mul(state.Psi, state.P0), matrix_transpose(state.Psi)),
        state.Omega,
    )
    return matrix_sub(state.P, rhs)


def decomposition_identity_enclosed(state: JointWordState) -> bool:
    return _contains_zero(decomposition_residual(state))


def predict(
    state: JointWordState,
    F: Sequence[Sequence[Interval]],
    Q: Sequence[Sequence[Interval]],
) -> None:
    n = state.dimension
    if _shape(F) != (n, n) or _shape(Q) != (n, n):
        raise ValueError("prediction F/Q dimension mismatch")
    Ft = matrix_transpose(F)
    state.P = matrix_symmetric_hull(
        matrix_add(matrix_mul(matrix_mul(F, state.P), Ft), Q)
    )
    state.Psi = matrix_mul(F, state.Psi)
    state.Omega = matrix_symmetric_hull(
        matrix_add(matrix_mul(matrix_mul(F, state.Omega), Ft), Q)
    )
    state.events += 1
    state.predictions += 1
    if not decomposition_identity_enclosed(state):
        raise RuntimeError("P/Psi/Omega identity lost after prediction")


def joseph_measurement(
    state: JointWordState,
    H: Sequence[Sequence[Interval]],
    R: Sequence[Sequence[Interval]],
) -> dict:
    n = state.dimension
    rows, cols = _shape(H)
    if cols != n or rows == 0 or _shape(R) != (rows, rows):
        raise ValueError("measurement H/R dimension mismatch")

    Ht = matrix_transpose(H)
    PHt = matrix_mul(state.P, Ht)
    S = matrix_symmetric_hull(
        matrix_add(matrix_mul(H, PHt), R)
    )
    Sinv = matrix_inverse_gauss_jordan(S)
    K = matrix_mul(PHt, Sinv)
    A = matrix_sub(matrix_identity(n), matrix_mul(K, H))
    At = matrix_transpose(A)
    KRKt = matrix_mul(matrix_mul(K, R), matrix_transpose(K))

    state.P = matrix_symmetric_hull(
        matrix_add(matrix_mul(matrix_mul(A, state.P), At), KRKt)
    )
    state.Psi = matrix_mul(A, state.Psi)
    state.Omega = matrix_symmetric_hull(
        matrix_add(matrix_mul(matrix_mul(A, state.Omega), At), KRKt)
    )
    state.events += 1
    state.measurements += 1
    if not decomposition_identity_enclosed(state):
        raise RuntimeError("P/Psi/Omega identity lost after Joseph measurement")
    return {"S": S, "K": K, "A": A}


def add_psd_floor(
    state: JointWordState,
    Delta_full: Sequence[Sequence[Interval]],
) -> None:
    n = state.dimension
    if _shape(Delta_full) != (n, n):
        raise ValueError("floor increment dimension mismatch")
    D = matrix_symmetric_hull(Delta_full)
    state.P = matrix_symmetric_hull(matrix_add(state.P, D))
    state.Omega = matrix_symmetric_hull(matrix_add(state.Omega, D))
    state.events += 1
    state.floors += 1
    if not decomposition_identity_enclosed(state):
        raise RuntimeError("P/Psi/Omega identity lost after covariance-floor event")


def contraction_matrix(
    state: JointWordState,
    delta: float = USEFUL_GATE,
) -> IntervalMatrix:
    if not (math.isfinite(delta) and delta > 0.0):
        raise ValueError("delta must be finite positive")
    return matrix_symmetric_hull(matrix_sub(state.Omega, _scale(state.P, delta)))


def certify_contraction(
    state: JointWordState,
    delta: float = USEFUL_GATE,
) -> dict:
    M = contraction_matrix(state, delta)
    passed, pivots = symmetric_positive_definite_ldlt(M)
    return {
        "dimension": state.dimension,
        "delta": float(delta),
        "Omega_minus_delta_P_ldlt_closed": bool(passed),
        "ldlt_pivots": [x.as_list() for x in pivots],
        "events": state.events,
        "predictions": state.predictions,
        "measurements": state.measurements,
        "floors": state.floors,
        "decomposition_identity_enclosed": decomposition_identity_enclosed(state),
        "pass": bool(passed and decomposition_identity_enclosed(state)),
    }


def _self_test() -> dict:
    """Arithmetic-kernel test only; this is not an OU-III theorem witness."""
    P0 = matrix_point([[2.0, 0.1], [0.1, 3.0]])
    state = initialize(P0)
    F = matrix_point([[1.0, 0.1], [0.0, 1.0]])
    Q = matrix_point([[0.02, 0.0], [0.0, 0.01]])
    predict(state, F, Q)
    H = matrix_point([[1.0, 0.0]])
    R = matrix_point([[0.5]])
    joseph_measurement(state, H, R)
    add_psd_floor(state, matrix_point([[0.0, 0.0], [0.0, 0.03]]))
    cert = certify_contraction(state, USEFUL_GATE)
    cert["shipping_source_parity"] = shipping_source_parity()
    cert["shipping_source_parity_pass"] = all(cert["shipping_source_parity"].values())
    cert["kernel_self_test_only_not_P3"] = True
    return cert


def validate_backend() -> list[str]:
    f: list[str] = []
    parity = shipping_source_parity()
    for name, ok in parity.items():
        if not ok:
            f.append(f"shipping source parity failed: {name}")
    try:
        test = _self_test()
    except Exception as exc:
        f.append(f"joint algebra self-test failed: {type(exc).__name__}: {exc}")
        return f
    if test.get("decomposition_identity_enclosed") is not True:
        f.append("joint algebra self-test lost covariance decomposition")
    if test.get("Omega_minus_delta_P_ldlt_closed") is not True:
        f.append("joint algebra self-test did not close positive test matrix")
    if test.get("kernel_self_test_only_not_P3") is not True:
        f.append("kernel self-test was misclassified")
    return list(dict.fromkeys(f))


if __name__ == "__main__":
    failures = validate_backend()
    print({
        "qualification": "OU3_SEA3_JOINT_P_PSI_OMEGA_ALGEBRA_BACKEND",
        "useful_gate": USEFUL_GATE,
        "failures": failures,
        "self_test": _self_test() if not failures else None,
        "P3_promoted": False,
    })
    raise SystemExit(0 if not failures else 2)
