def _shape(A: Sequence[Sequence[Interval]]) -> tuple[int, int]:
    rows = len(A)
    cols = len(A[0]) if rows else 0
    if any(len(row) != cols for row in A):
        raise ValueError("ragged interval matrix")
    return rows, cols


def _zero(rows: int, cols: int) -> IntervalMatrix:
    z = Interval.point(0.0)
    return [[z for _ in range(cols)] for _ in range(rows)]


def _scale(A: Sequence[Sequence[Interval]], c: float) -> IntervalMatrix:
    ci = Interval.outward_bounds(float(c), float(c))
    return [[ci * A[i][j] for j in range(len(A[i]))] for i in range(len(A))]


def _contains_zero(A: Sequence[Sequence[Interval]]) -> bool:
    return all(x.lo <= 0.0 <= x.hi for row in A for x in row)


def _copy(A: Sequence[Sequence[Interval]]) -> IntervalMatrix:
    return [[x for x in row] for row in A]


