#!/usr/bin/env python3
"""Validated algebraic backend for the canonical OU-III SEA3 P3 word.

This module is *not* a reduced P3 route. It implements exact full-matrix
bookkeeping for one already-enclosed source/event word. The word assembler must
supply the actual interval F, Q, H, R and covariance-floor events generated by
the complete Normal-Live source.

The direct joint recursion propagates

    P_k = Psi_k P_0 Psi_k^T + Omega_k.

Prediction:

    P-     = F P F^T + Q
    Psi-   = F Psi
    Omega- = F Omega F^T + Q

Joseph measurement correction:

    S  = H P- H^T + R
    K  = P- H^T S^-1
    A  = I - K H
    P+     = A P- A^T + K R K^T
    Psi+   = A Psi-
    Omega+ = A Omega- A^T + K R K^T.

For M_delta = Omega-delta P and 0<=delta<=1, every shipping event preserves an
already-established inequality M_delta>=0:

    prediction: M' = F M F^T + (1-delta) Q,
    Joseph:      M' = A M A^T + (1-delta) K R K^T,
    PSD floor:   M' = M + (1-delta) Delta.

This identity may shorten post-closure propagation but never permits omission
of events needed to establish the first closure.

The same complete word also admits an exact *prior-free batch factorization*.
Condition on all measurements processed so far while treating the word-start
error x0 as an unknown deterministic parameter. Carry

    D   accumulated information about x0,
    T   conditional map x0 -> current state,
    Qc  conditional covariance of process/measurement noise.

Start with D=0,T=I,Qc=0. For prediction,

    T <- F T,
    Qc <- F Qc F^T + Q.

For a Joseph measurement, with J=H T and S0=H Qc H^T+R,

    D  <- D + J^T S0^-1 J,
    K0  = Qc H^T S0^-1,
    T  <- (I-K0 H)T,
    Qc <- (I-K0 H)Qc(I-K0 H)^T + K0 R K0^T.

These are the innovation factorization of the *same* stacked linear-Gaussian
word; there is no zero-start concavity argument. At the endpoint, for every SPD
word-start covariance P0,

    Z = (P0^-1 + D)^-1,
    P_W     = T Z T^T + Qc,
    Psi_W   = T Z P0^-1,
    Omega_W = T Z D Z T^T + Qc.

Therefore

    Omega_W-delta P_W
      = T (Z D Z-delta Z) T^T + (1-delta)Qc.

Completing the square exactly gives

    Z D Z-delta Z >= -(delta^2/4) D^-1,

so the single full-matrix condition

    (1-delta) Qc - (delta^2/4) T D^-1 T^T >= 0

is sufficient for the canonical contraction **for every SPD P0**. This is not
a D_W/L_W product: D,T,Qc are produced jointly by the same event word and the
condition is one full matrix inequality. The complete-word assembler must still
include all source-required events. A covariance-floor increment can enter the
prior-free recursion exactly only when the supplied increment is independent
of P0; source floors whose magnitude depends on the actual Riccati covariance
must be enclosed by the assembler rather than silently treated as independent.

The theorem-level contraction test remains full-matrix interval LDL^T. No
one-step ratio, determinant/trace scalarization, scalar beta, blockwise minimum,
or source-history graph can promote through this backend.
"""
