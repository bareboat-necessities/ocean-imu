// Simulated truth of the shared-mode model itself (double): x' = A x + noise
// with the Hermitian excitation S; returns per step [p(3), v(3), a(3)].
struct ModelTruth {
    kc::CarmaSharedModeMotion<double> m;
    Eigen::Matrix<double,24,24> F, L;
    Eigen::Matrix<double,24,1> x;
    std::mt19937_64 rng;
    std::normal_distribution<double> n01{0.0, 1.0};
    ModelTruth(const kc::Hermitian3<double>& S, double kappa, double h, uint64_t seed) : rng(seed) { set(S, kappa, h, true); }
    void set(const kc::Hermitian3<double>& S, double kappa, double h, bool init) {
        Cfg c; c.source = Cfg::Source::External; c.shrink = false;
        m.coupling().set_config(c);
        m.coupling().set_external(S);
        m.set_vertical(kappa, std::sqrt(S.re(2,2)));
        m.set_horizontal(kappa, std::sqrt(S.re(0,0)), std::sqrt(S.re(1,1)), 0.0);
        m.refresh(h);
        F.setZero();
        for (int a = 0; a < 3; ++a) F.block<8,8>(8 * a, 8 * a) = m.block_F();
        Eigen::Matrix<double,24,24> Q = Eigen::Matrix<double,24,24>::Zero();
        m.propagate(Q, 0);
        L = sqrtm(Q);
        if (init) {
            Eigen::Matrix<double,24,24> P;
            m.stationary(P, 0);
            const Eigen::Matrix<double,24,24> Lp = sqrtm(P);
            Eigen::Matrix<double,24,1> w; for (int i = 0; i < 24; ++i) w(i) = n01(rng);
            x = Lp * w;
        }
    }
    static Eigen::Matrix<double,24,24> sqrtm(const Eigen::Matrix<double,24,24>& Q) {
        Eigen::SelfAdjointEigenSolver<Eigen::Matrix<double,24,24>> es(0.5 * (Q + Q.transpose()));
        return es.eigenvectors() * es.eigenvalues().cwiseMax(0.0).cwiseSqrt().asDiagonal();
    }
    void step() {
        Eigen::Matrix<double,24,1> w; for (int i = 0; i < 24; ++i) w(i) = n01(rng);
        x = F * x + L * w;
    }
    V3<double> p() const { return V3<double>(x(0), x(8), x(16)); }
    V3<double> v() const { return V3<double>(x(1), x(9), x(17)); }
    V3<double> a() const { return V3<double>(x(2), x(10), x(18)); }
};

kc::Hermitian3<double> directional(double dir_rad, double coh = 0.9) {
    // Long-crested sea from direction dir: horizontal displacement along it,
    // in quadrature with z (NED z down: +90 deg), horizontal amplitude 0.6.
    const double c = std::cos(dir_rad), s = std::sin(dir_rad);
    Eigen::Vector3cd u(0.6 * c * std::complex<double>(0, 1), 0.6 * s * std::complex<double>(0, 1), 1.0);
    Eigen::Matrix3cd S = coh * u * u.adjoint();
    for (int i = 0; i < 3; ++i) S(i,i) = std::norm(u(i)) + 0.05;
    kc::Hermitian3<double> h; h.re = S.real(); h.im = S.imag();
    return h;
}

template<class Fl>
void run_model_matched(Fl& f, ModelTruth& tr, double T_s, double t_score, double& rms_h, double& rms_z, double& nees,
                       std::mt19937_64& rng, std::vector<double>* err_series = nullptr) {
    std::normal_distribution<double> n01(0.0, 1.0);
    const double h = 0.005;
    const long N = static_cast<long>(T_s / h);
    double se_h = 0, se_z = 0, sn = 0; long n = 0;
    for (long k = 0; k < N; ++k) {
        tr.step();
        const V3<double> acc = tr.a() - V3<double>(0, 0, G) + SIGMA_A * V3<double>(n01(rng), n01(rng), n01(rng));
        const V3<double> gyr = SIGMA_G * std::sqrt(1.0 / h) * V3<double>(n01(rng), n01(rng), n01(rng));
        f.time_update(gyr, h);
        f.measurement_update_acc_only(acc);
        if (k % 8 == 0) f.measurement_update_mag_only(kMagWorld + 0.8 * V3<double>(n01(rng), n01(rng), n01(rng)));
        const double t = static_cast<double>(k + 1) * h;
        const V3<double> ep = f.get_position() - tr.p(), ev = f.get_velocity() - tr.v();
        if (err_series && k % 200 == 0) err_series->push_back(ep.squaredNorm());
        if (t < t_score) continue;
        se_h += ep(0) * ep(0) + ep(1) * ep(1);
        se_z += ep(2) * ep(2);
        Eigen::Matrix<double,6,6> P;
        int idx[6] = {f.pos_index(0), f.pos_index(1), f.pos_index(2), f.vel_index(0), f.vel_index(1), f.vel_index(2)};
        for (int i = 0; i < 6; ++i) for (int j = 0; j < 6; ++j) P(i,j) = f.covariance_full()(idx[i], idx[j]);
        Eigen::Matrix<double,6,1> e; e << ep, ev;
        sn += e.dot(P.ldlt().solve(e));
        ++n;
    }
    const double dn = static_cast<double>(n);
    rms_h = std::sqrt(se_h / dn);
    rms_z = std::sqrt(se_z / dn);
    nees = sn / dn;
}

template<class Fl>
Fl model_filter(const kc::Hermitian3<double>& S_true, const kc::Hermitian3<double>* S_filter, double kappa) {
    Fl f = make_filter<Fl>();
    if constexpr (Fl::kMotion) {
        Cfg c; c.source = S_filter ? Cfg::Source::External : Cfg::Source::Off; c.shrink = false;
        f.motion().coupling().set_config(c);
        if (S_filter) f.motion().coupling().set_external(*S_filter);
    }
    configure(f, kappa, V3<double>(std::sqrt(S_true.re(0,0)), std::sqrt(S_true.re(1,1)), std::sqrt(S_true.re(2,2))));
    f.set_acc_bias_updates_enabled(false);
    init_known(f);
    return f;
}

