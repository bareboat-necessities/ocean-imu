void test4_stability() {
    std::printf("[4] stable dynamics and complexification\n");
    double max_re = -1e9, max_rho = 0, worst_psd = 0, worst_mca = -1e9;
    for (double kappa : {0.15, 0.3, 0.5, 1.0, 2.0, 3.2}) {
        Eigen::Matrix<double,8,8> A8;
        kc::coupled_detail::complexified_c41(kc::CARMA41_JONSWAP_SHAPE, kappa, A8);
        Eigen::EigenSolver<Eigen::Matrix<double,8,8>> es(A8);
        max_re = std::max(max_re, es.eigenvalues().real().maxCoeff() / kappa);
        kc::CarmaSharedModeMotion<double> m;
        m.set_vertical(kappa, 1.0); m.set_horizontal(kappa, 1.0, 1.0, 0.0); m.refresh(0.005);
        Eigen::EigenSolver<Eigen::Matrix<double,8,8>> ef(m.block_F());
        max_rho = std::max(max_rho, ef.eigenvalues().cwiseAbs().maxCoeff());
        kc::CarmaRaoMcarmaMotion<double> mc;
        mc.set_vertical(kappa, 1.0); mc.set_horizontal(kappa, 1.0, 1.0, 0.0); mc.refresh(0.005);
        Eigen::EigenSolver<Eigen::Matrix<double,26,26>> em(mc.joint_A());
        worst_mca = std::max(worst_mca, em.eigenvalues().real().maxCoeff());
        // Re-part spectrum of the realization vs |B/P|^2 of C41J.
        Eigen::Matrix<double,8,8> W = Eigen::Matrix<double,8,8>::Zero(); W(2,2) = W(6,6) = 1.0;
        for (double f : {0.02, 0.1, 0.2, 0.3, 0.37, 0.5, 0.8, 1.5, 3.0}) {
            const double fk = f * kappa;
            const std::complex<double> s(0.0, 2 * PI * fk);
            Eigen::Matrix<std::complex<double>,8,8> M = s * Eigen::Matrix<std::complex<double>,8,8>::Identity() - A8.cast<std::complex<double>>();
            const Eigen::Matrix<std::complex<double>,8,8> Rr = M.inverse();
            const std::complex<double> Spp = (Rr.row(0) * W.cast<std::complex<double>>() * Rr.row(0).adjoint())(0,0);
            const double ref = kc::carma_unit_psd<4>(kc::CARMA41_JONSWAP_SHAPE, kappa, fk);
            worst_psd = std::max(worst_psd, std::abs(Spp.real() / ref - 1.0));
        }
    }
    check(max_re < -1e-3, "complexified C41J: every pole strictly stable (max Re / kappa)", max_re, -1e-3);
    check(max_rho < 1.0, "SHM F_8 spectral radius < 1", max_rho, 1.0);
    check(worst_mca < 0.0, "MCA joint dynamics strictly stable", worst_mca, 0.0);
    check(worst_psd < 1e-9, "Re-part PSD of the complexified realization equals C41J |B/P|^2", worst_psd, 1e-9);
}

