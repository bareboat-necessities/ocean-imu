// Baseline and COR (coupling off) side by side; returns max |dp| / RMS p and
// the largest relative position-variance difference.
template<typename T>
void compare_cor_base(double& dp_rel, double& dvar) {
    const T kappa = T(0.85);
    const V3<T> sig(T(0.35), T(0.30), T(0.55));
    auto b = make_filter<Base<T>>();
    auto c = make_filter<COR<T>>();
    configure(b, kappa, sig); configure(c, kappa, sig);
    init_level(b); init_level(c);
    SynthImu imu;
    double dc = 0, pp = 0;
    dvar = 0;
    for (int k = 0; k < 60000; ++k) {
        V3<T> acc, gyr;
        imu.sample(0.005, acc, gyr);
        b.time_update(gyr, T(0.005)); c.time_update(gyr, T(0.005));
        b.measurement_update_acc_only(acc); c.measurement_update_acc_only(acc);
        dc = std::max(dc, double((c.get_position() - b.get_position()).cwiseAbs().maxCoeff()));
        pp += b.get_position().squaredNorm();
        for (int ax = 0; ax < 3; ++ax) {
            const double vb = b.covariance_full()(b.pos_index(ax), b.pos_index(ax));
            const double vc = c.covariance_full()(c.pos_index(ax), c.pos_index(ax));
            dvar = std::max(dvar, std::abs(vc - vb) / vb);
        }
    }
    dp_rel = dc / std::sqrt(pp / 60000.0);
}

void test1_reduction() {
    std::printf("[1] reduction to independent axes\n");
    {
        double dp, dv;
        compare_cor_base<double>(dp, dv);
        check(dp < 1e-9, "COR (coupling off) equals the baseline filter in double: max |dp| / RMS(p)", dp, 1e-9);
        check(dv < 1e-9, "COR (coupling off) position variance equals the baseline in double", dv, 1e-9);
        compare_cor_base<float>(dp, dv);
        check(dp < 1e-4, "COR (coupling off) equals the baseline filter in float (rounding): max |dp| / RMS(p)", dp, 1e-4);
        check(dv < 2e-3, "COR (coupling off) position variance equals the baseline in float (rounding)", dv, 2e-3);
    }
    const float kappa = 0.85f;
    const V3<float> sig(0.35f, 0.30f, 0.55f);
    auto b = make_filter<Base<float>>();
    auto c = make_filter<COR<float>>();
    auto s = make_filter<SHM<float>>();
    configure(b, kappa, sig); configure(c, kappa, sig); configure(s, kappa, sig);
    init_level(b); init_level(c); init_level(s);
    SynthImu imu;
    double ds = 0, pp = 0;
    for (int k = 0; k < 60000; ++k) {
        V3<float> acc, gyr;
        imu.sample(0.005, acc, gyr);
        b.time_update(gyr, 0.005f); c.time_update(gyr, 0.005f); s.time_update(gyr, 0.005f);
        b.measurement_update_acc_only(acc); c.measurement_update_acc_only(acc); s.measurement_update_acc_only(acc);
        const V3<float> pb = b.get_position();
        ds += (s.get_position() - pb).squaredNorm();
        pp += pb.squaredNorm();
    }
    const double prms = std::sqrt(pp / 60000.0);
    check(std::sqrt(ds / 60000.0) / prms < 2e-3, "SHM (coupling off, baseline law): RMS dp / RMS p", std::sqrt(ds / 60000.0) / prms, 2e-3);
    // SHM with a real excitation is COR in law.
    auto c2 = make_filter<COR<float>>();
    auto s2 = make_filter<SHM<float>>();
    std::mt19937_64 rng(3);
    kc::Hermitian3<float> S = random_psd<float>(rng, 0.7);
    for (auto* cfgp : {&c2.motion().coupling(), &s2.motion().coupling()}) {
        Cfg cf; cf.source = Cfg::Source::External; cf.shrink = false; cf.form = Cfg::Form::Real;
        cfgp->set_config(cf);
        cfgp->set_external(S);
    }
    const V3<float> sig2(std::sqrt(S.re(0,0)), std::sqrt(S.re(1,1)), std::sqrt(S.re(2,2)));
    configure(c2, kappa, sig2); configure(s2, kappa, sig2);
    init_level(c2); init_level(s2);
    SynthImu imu2;
    double d2 = 0, p2 = 0;
    for (int k = 0; k < 40000; ++k) {
        V3<float> acc, gyr;
        imu2.sample(0.005, acc, gyr);
        c2.time_update(gyr, 0.005f); s2.time_update(gyr, 0.005f);
        c2.measurement_update_acc_only(acc); s2.measurement_update_acc_only(acc);
        d2 += (s2.get_position() - c2.get_position()).squaredNorm();
        p2 += c2.get_position().squaredNorm();
    }
    check(std::sqrt(d2 / p2) < 3e-3, "SHM with a real excitation equals COR (law): RMS dp / RMS p", std::sqrt(d2 / p2), 3e-3);
    // MCA off: diagonal excitation; heave acceleration variance as requested.
    auto m = make_filter<MCA<double>>();
    configure(m, 0.85, V3<double>(0.35, 0.30, 0.55));
    const auto& e = m.motion().excitation();
    check(e.re(0,2) == 0.0 && e.im(0,2) == 0.0 && e.re(0,1) == 0.0, "MCA off: no cross-axis excitation");
    Eigen::Matrix<double,26,26> P0;
    m.motion().stationary(P0, 0);
    int idx[4]; double w[4];
    const int n = m.motion().accel_terms(2, idx, w);
    double var = 0;
    for (int i = 0; i < n; ++i) for (int j = 0; j < n; ++j) var += w[i] * w[j] * P0(idx[i], idx[j]);
    check(std::abs(std::sqrt(var) / 0.55 - 1.0) < 1e-6, "MCA heave acceleration std equals the requested amplitude",
          std::sqrt(var) / 0.55 - 1.0, 1e-6);
}

