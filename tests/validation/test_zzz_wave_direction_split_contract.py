class WaveDirectionPublicationSplitTests(unittest.TestCase):
    def test_split_files_are_owned_by_the_new_article(self):
        wave_article = (DOC / "kalman-wave-dir.tex").read_text(encoding="utf-8")
        ou_article = (DOC / "kalman_ou-w3d.tex").read_text(encoding="utf-8")
        fusion = (DOC / "w3d-fus-methods.tex-part").read_text(encoding="utf-8")

        self.assertIn("Single-IMU Wave-Direction", wave_article)
        self.assertIn(r"\input{w3d-frequency-tracking.tex-part}", wave_article)
        self.assertIn(r"\input{w3d-direction-methods.tex-part}", wave_article)
        self.assertIn(r"\input{w3d-wave-direction-results.tex-part}", wave_article)
        self.assertNotIn("OUValidationDirectionAbsError", ou_article)
        self.assertNotIn("w3d-direction-methods.tex-part", fusion)

    def test_overrides_are_installed(self):
        self.assertIs(
            core.ManuscriptMethodologyTests.test_the_deterministic_table_is_generated_not_typed,
            _the_deterministic_table_is_generated_not_typed,
        )
        self.assertIs(
            core.ManuscriptMethodologyTests.test_transition_and_secondary_ensembles_are_rescored,
            _transition_and_secondary_ensembles_are_rescored,
        )
        self.assertIs(
            core.ManuscriptMethodologyTests.test_tracker_and_heel_material_are_scoped_as_unevaluated_appendices,
            _tracker_and_heel_material_are_scoped_as_unevaluated_appendices,
        )
