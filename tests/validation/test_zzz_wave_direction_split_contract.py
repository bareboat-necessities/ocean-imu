"""Publication-contract overrides for the standalone wave-direction paper.

The historical OU validation suite predates the publication split and therefore
pins direction/tracker material to the OU--III manuscript.  These late-sorted
overrides keep the numerical evidence checks while asserting the new document
ownership: OU--III owns navigation/regularization, while ``kalman-wave-dir.tex``
owns carrier tracking, propagation axis, and travel sense.
"""

import re
import unittest
from pathlib import Path

import test_ou_validation as core


REPO_ROOT = Path(__file__).resolve().parents[2]
DOC = REPO_ROOT / "doc" / "kalman_ou_iii"


def _the_deterministic_table_is_generated_not_typed(self):
    ou_protocol = self.read("w3d-sim-charts.tex-part")
    generated = self.read("w3d-sim-results-generated.tex-part")
    wave_article = (DOC / "kalman-wave-dir.tex").read_text(encoding="utf-8")
    wave_results = (DOC / "w3d-wave-direction-results.tex-part").read_text(
        encoding="utf-8"
    )

    # The historical generated table remains archived evidence, but the OU
    # publication no longer imports its direction columns.
    self.assertIn("Generated by tools/ou_sim_table.py", generated)
    self.assertIn("tab:sim_results_rms_dir_basic", generated)
    self.assertNotIn("w3d-sim-results-generated.tex-part", ou_protocol)

    self.assertIn(r"\input{w3d-wave-direction-results.tex-part}", wave_article)
    self.assertIn("OUValidationDirectionAbsError", wave_results)
    self.assertIn("OUValidationTravelCorrect", wave_results)


def _transition_and_secondary_ensembles_are_rescored(self):
    protocol = self.read_flat("w3d-sim-charts.tex-part")
    results = self.read_flat("w3d-baseline-comparison.tex-part")
    generated = self.read_flat("w3d-ou-validation-results-generated.tex-part")
    wave_results = (DOC / "w3d-wave-direction-results.tex-part").read_text(
        encoding="utf-8"
    )

    # OU--III still owns its transition and second-spectrum motion evidence.
    self.assertIn("pure-start, crossfade, and pure-endpoint intervals", protocol)
    self.assertIn("whole-window transition percentages", results)
    self.assertIn("tab:ou_transition_segments", generated)
    self.assertIn("tab:ou_mc_pmstokes", generated)
    self.assertIn("OUValidationPMStokesDifference", results)
    self.assertIn("rather than pooled", results)

    # Direction evidence is retained in the committed numerical bundle but is
    # now interpreted and claimed only by the standalone direction article.
    self.assertNotIn("OUValidationDirectionAbsError", results)
    self.assertNotIn("OUValidationTravelCorrect", results)
    self.assertIn("OUValidationDirectionAbsError", wave_results)
    self.assertIn("OUValidationDirectionWorstAbsError", wave_results)
    self.assertIn("OUValidationTravelCorrect", wave_results)
    self.assertIn("truth", wave_results.lower())
    self.assertIn("FORWARD/BACKWARD", wave_results)


